-- Optional local file-delivery pipeline, loaded separately from the main demo.
INSERT INTO CFG_PIPELINES
    (PIPELINE_CODE, PIPELINE_NAME, REFRESH_TYPE, RUN_SCHEDULE, OVERLAP_POLICY)
VALUES ('FILE_DELIVERY', 'Delivered CSV files', 'INCREMENTAL', '* * * * *', 'SKIP');
INSERT INTO CFG_TASKS (TASK_CODE, TASK_TYPE, PIPELINE_ID, HANDLER)
SELECT 'wait', 'INGESTION', PIPELINE_ID, 'EVENT_WAIT' FROM CFG_PIPELINES
WHERE PIPELINE_CODE='FILE_DELIVERY' AND ACTIVE_FLAG='Y';
INSERT INTO CFG_TASKS (TASK_CODE, TASK_TYPE, PIPELINE_ID, HANDLER)
SELECT 'consume', 'INGESTION', PIPELINE_ID, 'PYTHON' FROM CFG_PIPELINES
WHERE PIPELINE_CODE='FILE_DELIVERY' AND ACTIVE_FLAG='Y';
INSERT INTO CFG_TASK_PARAMETERS (TASK_ID, PARAMETER_NAME, PARAMETER_VALUE)
SELECT TASK_ID, 'EVENT_FILE', 'inbox/*.csv' FROM CFG_TASKS
WHERE TASK_CODE='wait' AND PIPELINE_ID=(SELECT PIPELINE_ID FROM CFG_PIPELINES
    WHERE PIPELINE_CODE='FILE_DELIVERY' AND ACTIVE_FLAG='Y');
INSERT INTO CFG_TASK_PARAMETERS (TASK_ID, PARAMETER_NAME, PARAMETER_VALUE)
SELECT TASK_ID, 'EVENT_TIMEOUT_MINUTES', 'NONE' FROM CFG_TASKS
WHERE TASK_CODE='wait' AND PIPELINE_ID=(SELECT PIPELINE_ID FROM CFG_PIPELINES
    WHERE PIPELINE_CODE='FILE_DELIVERY' AND ACTIVE_FLAG='Y');
INSERT INTO CFG_TASK_PARAMETERS (TASK_ID, PARAMETER_NAME, PARAMETER_VALUE)
SELECT TASK_ID, 'SCRIPT_KIND','INGESTION' FROM CFG_TASKS
WHERE TASK_CODE='consume' AND PIPELINE_ID=(SELECT PIPELINE_ID FROM CFG_PIPELINES
    WHERE PIPELINE_CODE='FILE_DELIVERY' AND ACTIVE_FLAG='Y');
INSERT INTO CFG_TASK_PARAMETERS (TASK_ID, PARAMETER_NAME, PARAMETER_VALUE)
SELECT TASK_ID, 'SCRIPT_FILE', 'python_scripts/delivery.py' FROM CFG_TASKS
WHERE TASK_CODE='consume' AND PIPELINE_ID=(SELECT PIPELINE_ID FROM CFG_PIPELINES
    WHERE PIPELINE_CODE='FILE_DELIVERY' AND ACTIVE_FLAG='Y');
INSERT INTO CFG_TASK_PARAMETERS (TASK_ID, PARAMETER_NAME, PARAMETER_VALUE)
SELECT TASK_ID, 'INPUT_PARAMS', '{"files":"$$event_files"}' FROM CFG_TASKS
WHERE TASK_CODE='consume' AND PIPELINE_ID=(SELECT PIPELINE_ID FROM CFG_PIPELINES
    WHERE PIPELINE_CODE='FILE_DELIVERY' AND ACTIVE_FLAG='Y');
INSERT INTO CFG_TASK_DEPENDENCY (PIPELINE_ID, TASK_ID, DEPENDS_ON_TASK_ID, DEPENDENCY_TYPE)
SELECT p.PIPELINE_ID, downstream.TASK_ID, upstream.TASK_ID, 'SUCCESS'
FROM CFG_PIPELINES p
JOIN CFG_TASKS downstream ON downstream.PIPELINE_ID=p.PIPELINE_ID AND downstream.TASK_CODE='consume'
JOIN CFG_TASKS upstream ON upstream.PIPELINE_ID=p.PIPELINE_ID AND upstream.TASK_CODE='wait'
WHERE p.PIPELINE_CODE='FILE_DELIVERY' AND p.ACTIVE_FLAG='Y';
