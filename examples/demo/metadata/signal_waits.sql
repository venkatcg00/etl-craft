-- Apply after the team creates lnd.external_signals through its warehouse deployment.
INSERT INTO CFG_PIPELINES (PIPELINE_CODE, PIPELINE_NAME, REFRESH_TYPE)
VALUES ('SIGNAL_DELIVERY', 'External signal delivery', 'INCREMENTAL');
INSERT INTO CFG_TASKS (TASK_CODE,TASK_TYPE,PIPELINE_ID,HANDLER)
SELECT 'wait', 'INGESTION', PIPELINE_ID, 'EVENT_WAIT'
FROM CFG_PIPELINES WHERE PIPELINE_CODE='SIGNAL_DELIVERY';
INSERT INTO CFG_TASK_PARAMETERS (TASK_ID,PARAMETER_NAME,PARAMETER_VALUE)
SELECT TASK_ID,'EVENT_SQL','SELECT event_id,payload FROM lnd.external_signals WHERE event_name=''orders_ready'' AND received_at >= CURRENT_TIMESTAMP - INTERVAL ''7 days'''
FROM CFG_TASKS WHERE TASK_CODE='wait' AND PIPELINE_ID=(
    SELECT PIPELINE_ID FROM CFG_PIPELINES WHERE PIPELINE_CODE='SIGNAL_DELIVERY');
INSERT INTO CFG_TASK_PARAMETERS (TASK_ID,PARAMETER_NAME,PARAMETER_VALUE)
SELECT TASK_ID,'EVENT_KEY_COLUMN','event_id' FROM CFG_TASKS WHERE TASK_CODE='wait'
AND PIPELINE_ID=(SELECT PIPELINE_ID FROM CFG_PIPELINES WHERE PIPELINE_CODE='SIGNAL_DELIVERY');
INSERT INTO CFG_TASK_PARAMETERS (TASK_ID,PARAMETER_NAME,PARAMETER_VALUE)
SELECT TASK_ID,'EVENT_MAX_ROWS','10000' FROM CFG_TASKS WHERE TASK_CODE='wait'
AND PIPELINE_ID=(SELECT PIPELINE_ID FROM CFG_PIPELINES WHERE PIPELINE_CODE='SIGNAL_DELIVERY');
INSERT INTO CFG_TASKS (TASK_CODE,TASK_TYPE,PIPELINE_ID,HANDLER)
SELECT 'consume', 'INGESTION', PIPELINE_ID, 'PYTHON'
FROM CFG_PIPELINES WHERE PIPELINE_CODE='SIGNAL_DELIVERY';
INSERT INTO CFG_TASK_PARAMETERS (TASK_ID,PARAMETER_NAME,PARAMETER_VALUE)
SELECT TASK_ID,'SCRIPT_KIND','INGESTION' FROM CFG_TASKS WHERE TASK_CODE='consume'
AND PIPELINE_ID=(SELECT PIPELINE_ID FROM CFG_PIPELINES WHERE PIPELINE_CODE='SIGNAL_DELIVERY');
INSERT INTO CFG_TASK_PARAMETERS (TASK_ID,PARAMETER_NAME,PARAMETER_VALUE)
SELECT TASK_ID,'SCRIPT_FILE','python_scripts/signals.py' FROM CFG_TASKS WHERE TASK_CODE='consume'
AND PIPELINE_ID=(SELECT PIPELINE_ID FROM CFG_PIPELINES WHERE PIPELINE_CODE='SIGNAL_DELIVERY');
INSERT INTO CFG_TASK_DEPENDENCY (PIPELINE_ID,TASK_ID,DEPENDS_ON_TASK_ID,DEPENDENCY_TYPE)
SELECT downstream.PIPELINE_ID,downstream.TASK_ID,upstream.TASK_ID,'SUCCESS'
FROM CFG_TASKS downstream JOIN CFG_TASKS upstream ON upstream.PIPELINE_ID=downstream.PIPELINE_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=downstream.PIPELINE_ID
WHERE p.PIPELINE_CODE='SIGNAL_DELIVERY' AND downstream.TASK_CODE='consume' AND upstream.TASK_CODE='wait';
