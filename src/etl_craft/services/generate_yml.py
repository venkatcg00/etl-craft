"""``generate-yml``: a pipeline's DAG, or the global trigger DAG, as YAML for an orchestrator.

A pipeline's DAG has one task per active task, which runs ``etl-craft run --task_code``, between
an ``__init__`` task (``--init-only``) and a ``__finalize__`` task (``--finalize-only``) that runs
whatever happened. Each task carries one Airflow ``trigger_rule``, worked out from its run
condition and its dependencies' types. Only one run of the DAG goes at a time
(``max_active_runs: 1``), as only one run of a pipeline is ``IN-PROGRESS``.

In remote mode the DAG holds every scheduling rule, since the engine checks none (see
``execution.remote``): a dependency on another pipeline's task is a sensor step before the task,
and a dependency on another pipeline is a sensor step after ``__init__`` and before the tasks,
unless ``Global_dag`` is on and the global DAG triggers the pipelines in order. Rules the
orchestrator does not support raise ``RemoteUnsupportedError``.

In local mode the engine checks every rule itself when the run or the task starts. Where Airflow
has no exact rule (``N``, ``HAS_DATA``, or dependencies of mixed types) the permissive
``all_done`` is written, and the engine records the task ``SKIPPED`` if its condition is not met;
dependencies on other pipelines are listed for information.

The DAG's settings come from the pipeline's ``PIPELINE_PARAMETERS``, then Orchestration's DAG
defaults, then a built-in default.
"""

