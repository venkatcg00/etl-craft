SELECT c.CONTROL_ID AS control_id, c.ACTION AS action, c.TASK_ID AS task_id
FROM AUD_CONTROL_REQUESTS c WHERE c.PIPELINE_RUN_ID=:run_id
AND c.ACTION IN ('HOLD','STOP','ABORT')
AND NOT EXISTS (SELECT 1 FROM AUD_CONTROL_REQUESTS newer
WHERE newer.PIPELINE_RUN_ID=c.PIPELINE_RUN_ID AND newer.CONTROL_ID>c.CONTROL_ID
AND (newer.TASK_ID=c.TASK_ID OR (newer.TASK_ID IS NULL AND c.TASK_ID IS NULL)))
