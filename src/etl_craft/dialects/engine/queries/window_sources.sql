SELECT a.STARTED_AT AS started_at, a.STATUS AS status, a.LEASE_EXPIRES_AT AS lease_expires_at
FROM AUD_TASK_ATTEMPTS a JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID=a.TASK_RUN_ID
JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=t.PIPELINE_RUN_ID
WHERE r.PIPELINE_ID IN :pipeline_ids AND a.STARTED_AT IS NOT NULL
AND (a.STATUS='RUNNING' OR (
 a.STATUS IN ('LOST','FAILED','TIMED_OUT','CANCELLED')
 AND NOT EXISTS (SELECT 1 AS stopped FROM AUD_ATTEMPT_ACKNOWLEDGEMENTS proc
 JOIN AUD_ATTEMPT_ACKNOWLEDGEMENTS queries ON queries.ATTEMPT_ID=proc.ATTEMPT_ID
 WHERE proc.ATTEMPT_ID=a.ATTEMPT_ID AND proc.KIND='PROCESS' AND queries.KIND='QUERIES' LIMIT 1 OFFSET 0)
 AND NOT EXISTS (SELECT 1 AS settled FROM AUD_TASK_ATTEMPTS newer
                 WHERE newer.TASK_RUN_ID=a.TASK_RUN_ID AND newer.ATTEMPT_ID>a.ATTEMPT_ID
                 AND newer.STATUS='SUCCESS' LIMIT 1 OFFSET 0)
))
