SELECT x.PIPELINE_GRANT_ID AS grant_id,p.PROJECT_CODE AS project,
g.GROUP_NAME AS group_name,a.ACCOUNT_NAME AS account,x.GRANTEE_ROLE AS role,
x.PIPELINE_CODE AS pipeline,x.TAG AS tag,x.PERMISSION AS permission,x.ACTIVE_FLAG AS active_flag
FROM CFG_PIPELINE_GRANTS x LEFT JOIN CFG_GROUPS g ON g.GROUP_ID=x.GROUP_ID
LEFT JOIN CFG_ACCOUNTS a ON a.ACCOUNT_ID=x.ACCOUNT_ID
JOIN CFG_PROJECTS p ON p.PROJECT_ID=x.PROJECT_ID
WHERE p.PROJECT_CODE=:project
ORDER BY x.PIPELINE_GRANT_ID
