SELECT b.BUNDLE_ID AS bundle_id
FROM AUD_PROJECT_BUNDLES b
WHERE b.PROJECT_ID=:project_id AND b.CREATED_AT<:cutoff
AND (SELECT r.PIPELINE_RUN_ID FROM AUD_PIPELINES_RUN_LOG r WHERE r.BUNDLE_ID=b.BUNDLE_ID LIMIT 1) IS NULL
AND (SELECT r.REFRESH_ID FROM AUD_PIPELINE_REFRESHES r WHERE r.BUNDLE_ID=b.BUNDLE_ID LIMIT 1) IS NULL
AND b.BUNDLE_ID<>(SELECT latest.BUNDLE_ID FROM AUD_PROJECT_BUNDLES latest
WHERE latest.PROJECT_ID=b.PROJECT_ID AND latest.CONNECTIONS_APPROVED_FLAG='Y'
ORDER BY latest.CREATED_AT DESC,latest.BUNDLE_ID DESC LIMIT 1)
ORDER BY b.CREATED_AT,b.BUNDLE_ID LIMIT 100
