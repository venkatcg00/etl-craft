SELECT 1 AS accepted FROM AUD_TASK_RUN_LOG WHERE TASK_ID=:task_id
AND PIPELINE_RUN_ID=:run_id AND STATUS='SUCCESS'
AND EXISTS (SELECT 1 AS successful_attempt FROM AUD_TASK_ATTEMPTS a
 WHERE a.TASK_RUN_ID=AUD_TASK_RUN_LOG.TASK_RUN_ID AND a.STATUS='SUCCESS')
AND EXISTS (SELECT 1 AS accepted_file FROM AUD_UPLOADS WHERE PIPELINE_RUN_ID=:run_id AND STATUS<>'REFUSED')
