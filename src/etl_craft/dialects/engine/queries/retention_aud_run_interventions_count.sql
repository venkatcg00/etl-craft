SELECT
  COUNT(*) AS count
FROM AUD_RUN_INTERVENTIONS AS t
WHERE
 NOT EXISTS (SELECT 1 AS protected FROM AUD_TASK_OFFSET_TRACKER pending JOIN AUD_TASK_RUN_LOG owner ON owner.TASK_RUN_ID=pending.PENDING_TASK_RUN_ID WHERE pending.PENDING_TASK_RUN_ID IS NOT NULL AND owner.PIPELINE_RUN_ID=t.PIPELINE_RUN_ID LIMIT 1 OFFSET 0) AND
  (
    EXISTS(
      SELECT
        1
      FROM AUD_PIPELINES_RUN_LOG AS r
      JOIN CFG_PIPELINES AS p
        ON p.PIPELINE_ID = r.PIPELINE_ID
      WHERE
        p.PROJECT_ID = :project_id
        AND r.STATUS IN ('SUCCESS', 'FAILED', 'SKIPPED', 'CANCELLED')
        AND r.END_DATE < :cutoff
        AND r.PIPELINE_RUN_ID = t.PIPELINE_RUN_ID
      LIMIT 1
      OFFSET 0
    )
  )
  AND t.REQUESTED_AT < :cutoff
