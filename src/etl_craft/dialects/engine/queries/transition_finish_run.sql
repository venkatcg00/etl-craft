UPDATE AUD_PIPELINES_RUN_LOG SET STATUS = CAST(:status AS varchar),
OUTPUT_REVISION = CASE WHEN CAST(:status AS varchar)='SUCCESS' AND EXISTS (SELECT 1 FROM AUD_RUN_INTERVENTIONS i WHERE i.PIPELINE_RUN_ID=AUD_PIPELINES_RUN_LOG.PIPELINE_RUN_ID AND i.ACTION='PAUSE_APPLIED' AND i.TO_STATUS='SUCCESS' AND NOT EXISTS (
SELECT 1 FROM AUD_TASK_RUN_LOG actual JOIN AUD_TASK_ATTEMPTS a ON a.TASK_RUN_ID=actual.TASK_RUN_ID
WHERE actual.PIPELINE_RUN_ID=i.PIPELINE_RUN_ID AND actual.TASK_ID=i.TASK_ID AND a.STATUS='SUCCESS')) THEN 0 ELSE OUTPUT_REVISION + CASE WHEN CAST(:status AS varchar) = 'SUCCESS' AND REPAIR_PENDING = 'Y' THEN 1 ELSE 0 END END,
REPAIR_PENDING = CASE WHEN CAST(:status AS varchar) = 'SUCCESS' THEN 'N' ELSE REPAIR_PENDING END, END_DATE = :now,
ENDED_BY = :actor, ENDED_BY_KIND = :actor_kind,
SLA_BREACHED_AT = CASE WHEN SLA_BREACHED_AT IS NULL AND COALESCE(SLA_STATUS, :sla_status)='BREACHED' THEN :now ELSE SLA_BREACHED_AT END,
SLA_STATUS = COALESCE(SLA_STATUS, :sla_status)
WHERE PIPELINE_RUN_ID = :row_id AND STATUS = 'IN-PROGRESS' AND (OWNER_ID = :owner OR (OWNER_ID IS NULL AND :owner IS NULL))
AND (:owner IS NULL OR LEASE_EXPIRES_AT > :now)
AND NOT EXISTS (SELECT 1 FROM AUD_TASK_ATTEMPTS a
JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID = a.TASK_RUN_ID
WHERE t.PIPELINE_RUN_ID = AUD_PIPELINES_RUN_LOG.PIPELINE_RUN_ID
AND a.STATUS IN ('CLAIMED','RUNNING'))
