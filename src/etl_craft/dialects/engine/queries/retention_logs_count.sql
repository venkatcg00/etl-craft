SELECT COUNT(*) AS count
FROM AUD_TASK_ATTEMPTS a
JOIN AUD_TASK_RUN_LOG tr ON tr.TASK_RUN_ID=a.TASK_RUN_ID
JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=tr.PIPELINE_RUN_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
JOIN CFG_TASKS t ON t.TASK_ID=tr.TASK_ID
WHERE p.PROJECT_ID=:project_id AND a.LOG_REMOVED_AT IS NULL
AND a.STATUS NOT IN ('QUEUED','CLAIMED','RUNNING') AND a.ENDED_AT < :cutoff
AND r.STATUS IN ('SUCCESS','FAILED','SKIPPED','CANCELLED')
AND (a.LOG_PATH IS NOT NULL OR a.TASK_LOG IS NOT NULL OR EXISTS (
    SELECT 1 FROM AUD_ATTEMPT_LOG_CHUNKS c WHERE c.ATTEMPT_ID=a.ATTEMPT_ID))
