SELECT p.PIPELINE_ID AS pipeline_id,t.TASK_ID AS task_id
FROM CFG_PIPELINES p JOIN CFG_PROJECTS project ON project.PROJECT_ID=p.PROJECT_ID
LEFT JOIN CFG_TASKS t ON t.PIPELINE_ID=p.PIPELINE_ID AND t.TASK_CODE=:task_code AND t.ACTIVE_FLAG='Y'
WHERE project.PROJECT_CODE=:project_code AND project.ACTIVE_FLAG='Y'
AND p.PIPELINE_CODE=:pipeline_code AND p.ACTIVE_FLAG='Y'
AND (CAST(:task_code AS varchar) IS NULL OR t.TASK_ID IS NOT NULL)
