-- The latest finished row of :task_id under a run that is not part of a backfill, and whether
-- it wrote rows (by its TARGET_COUNT when it was recorded before ROWS_WRITTEN existed).
SELECT t.TASK_RUN_ID AS run_id, t.STATUS AS status, CASE WHEN EXISTS (SELECT 1 FROM AUD_RUN_INTERVENTIONS i WHERE i.PIPELINE_RUN_ID=r.PIPELINE_RUN_ID AND i.TASK_ID=t.TASK_ID AND i.ACTION='PAUSE_APPLIED' AND i.TO_STATUS='SUCCESS' AND NOT EXISTS (
SELECT 1 FROM AUD_TASK_RUN_LOG actual JOIN AUD_TASK_ATTEMPTS a ON a.TASK_RUN_ID=actual.TASK_RUN_ID
WHERE actual.PIPELINE_RUN_ID=i.PIPELINE_RUN_ID AND actual.TASK_ID=i.TASK_ID AND a.STATUS='SUCCESS')) THEN 0 ELSE r.OUTPUT_REVISION END AS revision, r.PIPELINE_RUN_ID AS pipeline_run_id,
       CASE WHEN COALESCE(t.ROWS_WRITTEN, t.TARGET_COUNT) > 0 THEN 1 ELSE 0 END AS has_data
FROM AUD_TASK_RUN_LOG t
JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID = t.PIPELINE_RUN_ID
WHERE t.TASK_ID = :task_id AND t.STATUS IN ('SUCCESS', 'FAILED', 'SKIPPED', 'CANCELLED')
  AND r.BACKFILL = 'N' AND r.TASK_SELECTION IS NULL
ORDER BY t.TASK_RUN_ID DESC
LIMIT 1
