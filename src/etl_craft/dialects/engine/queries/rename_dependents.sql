SELECT d.PIPELINE_ID AS pipeline_id,
(SELECT p.PROJECT_ID AS project_id FROM CFG_PIPELINES p
 WHERE p.PIPELINE_ID=d.PIPELINE_ID LIMIT 1 OFFSET 0) AS project_id,
(SELECT p.PIPELINE_CODE AS pipeline_code FROM CFG_PIPELINES p
 WHERE p.PIPELINE_ID=d.PIPELINE_ID LIMIT 1 OFFSET 0) AS pipeline_code
FROM CFG_PIPELINE_DEPENDENCY d WHERE d.DEPENDS_ON_PIPELINE_ID=:pipeline_id
UNION
SELECT d.PIPELINE_ID AS pipeline_id,
(SELECT p.PROJECT_ID AS project_id FROM CFG_PIPELINES p
 WHERE p.PIPELINE_ID=d.PIPELINE_ID LIMIT 1 OFFSET 0) AS project_id,
(SELECT p.PIPELINE_CODE AS pipeline_code FROM CFG_PIPELINES p
 WHERE p.PIPELINE_ID=d.PIPELINE_ID LIMIT 1 OFFSET 0) AS pipeline_code
FROM CFG_TASK_DEPENDENCY d WHERE d.DEPENDS_ON_PIPELINE_ID=:pipeline_id
