SELECT x.GROUP_ID AS group_id,x.ACCOUNT_ID AS account_id,a.ACCOUNT_NAME AS account_name,
a.ACTIVE_FLAG AS account_active,x.GRANTEE_ROLE AS grantee_role,
x.PIPELINE_CODE AS pipeline_code,x.TAG AS tag,x.PERMISSION AS permission
FROM CFG_PIPELINE_GRANTS x LEFT JOIN CFG_ACCOUNTS a ON a.ACCOUNT_ID=x.ACCOUNT_ID
WHERE x.ACTIVE_FLAG='Y' AND x.PROJECT_ID=:project_id
