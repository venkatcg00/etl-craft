SELECT
  COUNT(*) AS count
FROM AUD_BUSINESS_RULES_RESULTS AS t
WHERE
  (
    EXISTS(
      SELECT
        1
      FROM AUD_BUSINESS_RULES_RUN_LOG AS br
      JOIN AUD_TASK_RUN_LOG AS tr
        ON tr.TASK_RUN_ID = br.TASK_RUN_ID
      JOIN AUD_PIPELINES_RUN_LOG AS r
        ON r.PIPELINE_RUN_ID = tr.PIPELINE_RUN_ID
      JOIN CFG_PIPELINES AS p
        ON p.PIPELINE_ID = r.PIPELINE_ID
      WHERE
        br.BUSINESS_RULE_RUN_ID = t.BUSINESS_RULE_RUN_ID
        AND p.PROJECT_ID = :project_id
        AND r.STATUS IN ('SUCCESS', 'FAILED', 'SKIPPED', 'CANCELLED')
        AND r.END_DATE < :cutoff
      LIMIT 1
      OFFSET 0
    )
  )
  AND t.ACTIVE_FLAG = 'N'
  AND t.END_DATE < :cutoff
