DELETE FROM AUD_GATE_WAITS WHERE (PIPELINE_RUN_ID,COALESCE(TASK_ID,-1)) IN (
SELECT t.PIPELINE_RUN_ID AS pipeline_run_id,COALESCE(t.TASK_ID,-1) AS task_id FROM AUD_GATE_WAITS t
JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=t.PIPELINE_RUN_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
WHERE p.PROJECT_ID=:project_id AND r.STATUS IN ('SUCCESS','FAILED','SKIPPED','CANCELLED')
AND r.END_DATE < :cutoff ORDER BY t.PIPELINE_RUN_ID,t.TASK_ID LIMIT 10000)
