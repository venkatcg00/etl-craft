SELECT TABLE_ID AS table_id, CATALOG_NAME AS catalog_name, SCHEMA_NAME AS schema_name,
TABLE_NAME AS table_name, OBJECT_KIND AS object_kind, REJECT_RETENTION_DAYS AS reject_retention_days,
SNAPSHOT_RETENTION_DAYS AS snapshot_retention_days, ORPHAN_RETENTION_DAYS AS orphan_retention_days
FROM CFG_TABLES WHERE PROJECT_ID=:project_id AND
(REJECT_RETENTION_DAYS IS NOT NULL OR SNAPSHOT_RETENTION_DAYS IS NOT NULL OR ORPHAN_RETENTION_DAYS IS NOT NULL)
ORDER BY TABLE_ID
