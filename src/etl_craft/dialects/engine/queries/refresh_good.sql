SELECT r.REFRESH_ID AS refresh_id,r.METADATA_VERSION AS metadata_version,r.BUNDLE_ID AS bundle_id,
COALESCE(r.METADATA_SNAPSHOT,s.METADATA_SNAPSHOT) AS snapshot
FROM AUD_PIPELINE_REFRESHES r LEFT JOIN AUD_PIPELINE_REFRESHES s ON s.REFRESH_ID=r.SNAPSHOT_REFRESH_ID
WHERE r.PIPELINE_ID=:pipeline_id AND r.STATUS='SUCCESS'
ORDER BY r.REFRESH_ID DESC LIMIT 1
