SELECT r.PIPELINE_RUN_ID AS child_run_id, p.PIPELINE_CODE AS child_code,
       c.PIPELINE_RUN_ID AS parent_run_id, c.CONTROL_ID AS control_id,
       c.ACTION AS action
FROM AUD_CONTROL_REQUESTS c
JOIN AUD_GATE_WAITS w ON w.PIPELINE_RUN_ID=c.PIPELINE_RUN_ID
 AND w.WAIT_KIND='PIPELINE_RUN' AND w.NEXT_CHECK_AT IS NOT NULL
JOIN AUD_TASK_RUN_LOG t ON t.PIPELINE_RUN_ID=w.PIPELINE_RUN_ID AND t.TASK_ID=w.TASK_ID
JOIN AUD_PIPELINES_RUN_LOG r ON r.TRIGGERED_BY_TASK_RUN_ID=t.TASK_RUN_ID
 AND r.RUN_KEY='trigger:' || CAST(t.TASK_RUN_ID AS varchar) || ':' || CAST(t.TRIGGER_GENERATION AS varchar)
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
WHERE (c.TASK_ID IS NULL OR c.TASK_ID=w.TASK_ID) AND c.ACTION IN ('STOP','ABORT')
AND c.REQUESTED_AT>=w.FIRST_CHECK_AT
AND r.STATUS IN ('QUEUED','IN-PROGRESS')
AND (CAST(:run_id AS bigint) IS NULL OR c.PIPELINE_RUN_ID=:run_id)
ORDER BY c.CONTROL_ID,r.PIPELINE_RUN_ID
