SELECT 'run' AS kind, CAST(PIPELINE_RUN_ID AS varchar) AS identity, STATUS AS value
FROM AUD_PIPELINES_RUN_LOG WHERE PIPELINE_ID=:pipeline_id AND STATUS IN ('QUEUED','IN-PROGRESS')
UNION ALL SELECT 'pending window' AS kind, CAST(o.TASK_ID AS varchar) AS identity,
CAST(o.PENDING_TASK_RUN_ID AS varchar) AS value FROM AUD_TASK_OFFSET_TRACKER o
JOIN CFG_TASKS t ON t.TASK_ID=o.TASK_ID WHERE t.PIPELINE_ID=:pipeline_id AND o.PENDING_TASK_RUN_ID IS NOT NULL
