SELECT RESERVATION_ID AS reservation_id,ROLE AS role,HOST AS host,PID AS pid,
POOL_CONNECTIONS AS pool_connections,SESSION_CONNECTIONS AS session_connections,
LOCAL_TASK_CONNECTIONS AS local_task_connections,HEARTBEAT_AT AS heartbeat_at,EXPIRES_AT AS expires_at
FROM AUD_CONNECTION_RESERVATIONS WHERE STOPPED_AT IS NULL AND EXPIRES_AT>:now
ORDER BY RESERVATION_ID
