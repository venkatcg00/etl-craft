SELECT a.PIPELINE_PAUSE_ID AS pause_id,a.PIPELINE_ID AS pipeline_id,a.TASK_ID AS task_id,
a.OUTCOME AS outcome,a.EXPIRES_AT AS expires_at,a.PAUSED_AT AS paused_at,a.PAUSED_BY AS actor,
a.REASON AS reason,t.TASK_CODE AS task_code FROM AUD_PIPELINE_PAUSES a
JOIN CFG_TASKS t ON t.TASK_ID=a.TASK_ID JOIN CFG_PIPELINES p ON p.PIPELINE_ID=a.PIPELINE_ID
WHERE (:pipeline_id IS NULL OR a.PIPELINE_ID=:pipeline_id)
AND (:pipeline_id IS NOT NULL OR p.PROJECT_ID=:project_id)
AND a.RESUMED_AT IS NULL ORDER BY a.TASK_ID
