SELECT g.GROUP_ID AS group_id, CASE WHEN m.GROUP_MEMBER_ID IS NULL THEN 'N' ELSE 'Y' END AS explicit_member
FROM CFG_GROUPS g JOIN CFG_ACCOUNTS a ON a.ACCOUNT_NAME=:account AND a.ACTIVE_FLAG='Y'
LEFT JOIN CFG_GROUP_MEMBERS m ON m.GROUP_ID=g.GROUP_ID AND m.ACCOUNT_ID=a.ACCOUNT_ID AND m.ACTIVE_FLAG='Y'
WHERE g.ACTIVE_FLAG='Y'
