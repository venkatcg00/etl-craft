SELECT a.ATTEMPT_ID AS attempt_id, a.STATUS AS status,
a.HOST AS host, a.PID AS pid, a.PROCESS_START AS process_start,
proc.OBSERVED_AT AS process_ended_at, queries.OBSERVED_AT AS queries_ended_at,
t.TASK_ID AS task_id, cfg.HANDLER AS handler, a.OWNER_ID AS owner_id
FROM AUD_TASK_ATTEMPTS a JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID=a.TASK_RUN_ID
JOIN CFG_TASKS cfg ON cfg.TASK_ID=t.TASK_ID
LEFT JOIN AUD_ATTEMPT_ACKNOWLEDGEMENTS proc ON proc.ATTEMPT_ID=a.ATTEMPT_ID AND proc.KIND='PROCESS'
LEFT JOIN AUD_ATTEMPT_ACKNOWLEDGEMENTS queries ON queries.ATTEMPT_ID=a.ATTEMPT_ID AND queries.KIND='QUERIES'

WHERE t.PIPELINE_RUN_ID=:run_id AND (CAST(:task_id AS bigint) IS NULL OR t.TASK_ID=:task_id)
AND (a.STATUS IN ('QUEUED','CLAIMED','RUNNING')
OR ((a.PID IS NOT NULL OR a.STATUS='LOST')
AND (proc.OBSERVED_AT IS NULL OR queries.OBSERVED_AT IS NULL)))
