DELETE FROM AUD_GATE_DECISIONS WHERE DECISION_ID IN (
SELECT t.DECISION_ID AS row_id FROM AUD_GATE_DECISIONS t WHERE (EXISTS (SELECT 1 FROM AUD_PIPELINES_RUN_LOG r JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID WHERE p.PROJECT_ID=:project_id AND r.STATUS IN ('SUCCESS','FAILED','SKIPPED','CANCELLED') AND r.END_DATE < :cutoff AND r.PIPELINE_RUN_ID=t.PIPELINE_RUN_ID)) AND t.DECIDED_AT < :cutoff
ORDER BY t.DECISION_ID LIMIT 10000
)
