SELECT r.TASK_RUN_ID AS task_run_id,r.TASK_ID AS task_id,t.HANDLER AS handler,
p.PIPELINE_ID AS pipeline_id,r.PIPELINE_RUN_ID AS run_id,r.STATUS AS status,
(SELECT MAX(a.ATTEMPT_ID) AS attempt_id FROM AUD_TASK_ATTEMPTS a WHERE a.TASK_RUN_ID=r.TASK_RUN_ID) AS attempt_id
FROM AUD_TASK_RUN_LOG r JOIN CFG_TASKS t ON t.TASK_ID=r.TASK_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=t.PIPELINE_ID
WHERE r.PIPELINE_RUN_ID=:run_id AND p.PROJECT_ID=:project_id AND p.PIPELINE_CODE=:pipeline_code AND t.TASK_CODE=:task_code
