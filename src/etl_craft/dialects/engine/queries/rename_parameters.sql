SELECT x.TASK_PARAMETER_ID AS parameter_id, x.PARAMETER_NAME AS name, x.PARAMETER_VALUE AS value,
p.PIPELINE_ID AS pipeline_id,p.PIPELINE_CODE AS pipeline_code,t.TASK_CODE AS task_code
FROM CFG_TASK_PARAMETERS x JOIN CFG_TASKS t ON t.TASK_ID=x.TASK_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=t.PIPELINE_ID
WHERE p.PROJECT_ID=:project_id AND x.PARAMETER_NAME IN ('TRIGGER_PIPELINE_CODE','WATERMARK_SOURCE_PIPELINES')
ORDER BY x.TASK_PARAMETER_ID
