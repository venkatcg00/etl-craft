-- What running :task_id needs beyond its parameters.
SELECT COALESCE((SELECT v.PARAMETER_VALUE FROM CFG_TASK_PARAMETERS v
WHERE v.TASK_ID=t.TASK_ID AND v.PARAMETER_NAME='POOL' AND v.ACTIVE_FLAG='Y'),(SELECT project.DEFAULT_POOL FROM CFG_PROJECTS project WHERE project.PROJECT_ID=p.PROJECT_ID)) AS pool,
(SELECT g.ACTIVE_FLAG FROM CFG_POOLS g WHERE g.POOL_NAME=COALESCE(
(SELECT v.PARAMETER_VALUE FROM CFG_TASK_PARAMETERS v WHERE v.TASK_ID=t.TASK_ID
AND v.PARAMETER_NAME='POOL' AND v.ACTIVE_FLAG='Y'),(SELECT project.DEFAULT_POOL FROM CFG_PROJECTS project WHERE project.PROJECT_ID=p.PROJECT_ID))) AS pool_active,
t.HANDLER AS handler, t.TASK_CODE AS task_code, t.PIPELINE_ID AS pipeline_id,
       p.PIPELINE_CODE AS pipeline_code, p.REFRESH_TYPE AS refresh_type
FROM CFG_TASKS t
JOIN CFG_PIPELINES p ON p.PIPELINE_ID = t.PIPELINE_ID
WHERE t.TASK_ID = :task_id
