SELECT COALESCE(SUM(a.RESERVED_CPU),0) AS cpu_used,
COALESCE(SUM(a.RESERVED_MEMORY_MB),0) AS memory_used_mb,
COUNT(*) AS slots_used,
COUNT(CASE WHEN a.SLOT_KIND='python' THEN 1 END) AS python_used,
COUNT(CASE WHEN a.SLOT_KIND='warehouse' THEN 1 END) AS warehouse_used
FROM AUD_TASK_ATTEMPTS a WHERE a.HOST=:host AND a.STATUS IN ('CLAIMED','RUNNING')
