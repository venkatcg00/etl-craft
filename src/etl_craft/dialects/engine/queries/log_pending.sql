SELECT a.ATTEMPT_ID AS attempt_id FROM AUD_TASK_ATTEMPTS a
WHERE a.LOG_PATH IS NULL AND a.LOG_REMOVED_AT IS NULL
AND a.STATUS NOT IN ('QUEUED','CLAIMED','RUNNING')
AND a.ATTEMPT_ID>:after_id
AND EXISTS (SELECT 1 FROM AUD_ATTEMPT_LOG_CHUNKS c WHERE c.ATTEMPT_ID=a.ATTEMPT_ID LIMIT 1 OFFSET 0)
ORDER BY a.ATTEMPT_ID LIMIT 100
