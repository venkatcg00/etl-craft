SELECT CONTROL_ID AS control_id, REQUEST_KEY AS request_key, ACTION AS action,
STATUS AS status, PIPELINE_RUN_ID AS pipeline_run_id, TASK_ID AS task_id
FROM AUD_CONTROL_REQUESTS WHERE PIPELINE_RUN_ID=:run_id
AND (TASK_ID=CAST(:task_id AS bigint) OR (TASK_ID IS NULL AND CAST(:task_id AS bigint) IS NULL))
ORDER BY CONTROL_ID DESC LIMIT 1
