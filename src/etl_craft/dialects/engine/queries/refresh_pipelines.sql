SELECT p.PIPELINE_ID AS pipeline_id,p.PIPELINE_CODE AS pipeline_code,
p.BLOCK_ON_REFRESH_ERROR AS block_on_refresh_error
FROM CFG_PIPELINES p WHERE p.PROJECT_ID=:project_id AND p.ACTIVE_FLAG='Y'
AND (CAST(:pipeline_code AS varchar) IS NULL OR p.PIPELINE_CODE=:pipeline_code)
AND (NOT :missing_only OR NOT EXISTS (SELECT 1 FROM AUD_PIPELINE_REFRESHES r WHERE r.PIPELINE_ID=p.PIPELINE_ID AND r.STATUS='SUCCESS'))
ORDER BY p.PIPELINE_CODE
