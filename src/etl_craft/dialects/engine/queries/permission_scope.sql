SELECT p.PIPELINE_CODE AS pipeline_code
FROM AUD_PIPELINES_RUN_LOG r JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
WHERE r.PIPELINE_RUN_ID=:run_id AND p.PROJECT_ID=:project_id
UNION
SELECT p.PIPELINE_CODE AS pipeline_code
FROM AUD_TASK_ATTEMPTS a JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID=a.TASK_RUN_ID
JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=t.PIPELINE_RUN_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
WHERE a.ATTEMPT_ID=:attempt_id AND p.PROJECT_ID=:project_id
UNION
SELECT p.PIPELINE_CODE AS pipeline_code
FROM AUD_CONTROL_REQUESTS c JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=c.PIPELINE_RUN_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID WHERE c.CONTROL_ID=:control_id AND p.PROJECT_ID=:project_id
UNION
SELECT p.PIPELINE_CODE AS pipeline_code
FROM AUD_TASK_RUN_LOG t JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=t.PIPELINE_RUN_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
WHERE t.TASK_RUN_ID=:task_run_id AND p.PROJECT_ID=:project_id
