SELECT i.ITEM_KEY AS key,i.ITEM_ATTEMPT_NUMBER AS number,i.STATUS AS status,
a.STATUS AS attempt_status,i.ROW_COUNT AS row_count,i.ERROR_MESSAGE AS error,i.STARTED_AT AS started,
CASE WHEN i.STATUS='CANCEL_REQUESTED' AND a.STATUS NOT IN ('CLAIMED','RUNNING','LOST')
THEN COALESCE(i.ENDED_AT,a.ENDED_AT) ELSE i.ENDED_AT END AS ended,i.REPORT_ID AS report_id,i.ATTEMPT_ID AS attempt_id
FROM AUD_TASK_ITEMS i JOIN AUD_TASK_ATTEMPTS a ON a.ATTEMPT_ID=i.ATTEMPT_ID WHERE i.TASK_RUN_ID=:task_run_id
AND (CAST(:key AS varchar) IS NULL OR i.ITEM_KEY=:key)
AND NOT EXISTS (SELECT 1 FROM AUD_TASK_ITEMS n WHERE n.TASK_RUN_ID=i.TASK_RUN_ID
AND n.ITEM_KEY=i.ITEM_KEY AND n.ITEM_RECORD_ID>i.ITEM_RECORD_ID)
ORDER BY i.ITEM_KEY
