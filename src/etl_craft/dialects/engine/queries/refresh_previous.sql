SELECT r.REFRESHED_AT AS refreshed_at,r.STATUS AS status,
COALESCE(r.METADATA_SNAPSHOT,s.METADATA_SNAPSHOT) AS snapshot,r.BUNDLE_ID AS bundle_id
FROM AUD_PIPELINE_REFRESHES r
LEFT JOIN AUD_PIPELINE_REFRESHES s ON s.REFRESH_ID=r.SNAPSHOT_REFRESH_ID
WHERE r.PIPELINE_ID=:pipeline_id
ORDER BY r.REFRESH_ID DESC LIMIT 1
