SELECT p.PROJECT_ID AS project_id,a.QUEUED_AT AS queued_at,
a.ATTEMPT_NUMBER AS attempt_number,a.STATUS AS status
FROM AUD_TASK_ATTEMPTS a JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID=a.TASK_RUN_ID
JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=t.PIPELINE_RUN_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID WHERE a.ATTEMPT_ID=:row_id
