DELETE FROM AUD_ATTEMPT_LOG_CHUNKS WHERE (ATTEMPT_ID,SEQUENCE_NUMBER) IN (
SELECT c.ATTEMPT_ID AS attempt_id,c.SEQUENCE_NUMBER AS sequence_number FROM AUD_ATTEMPT_LOG_CHUNKS c
JOIN AUD_TASK_ATTEMPTS a ON a.ATTEMPT_ID=c.ATTEMPT_ID
JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID=a.TASK_RUN_ID
JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=t.PIPELINE_RUN_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
WHERE p.PROJECT_ID=:project_id AND a.LOG_REMOVED_AT IS NOT NULL
ORDER BY c.ATTEMPT_ID,c.SEQUENCE_NUMBER LIMIT 10000)
