SELECT
  a.ATTEMPT_ID AS attempt_id,
  a.LOG_PATH AS log_path,
  a.ATTEMPT_NUMBER AS attempt_number,
  tr.TASK_RUN_ID AS task_run_id,
  r.PIPELINE_RUN_ID AS pipeline_run_id,
  p.PIPELINE_CODE AS pipeline_code,
  t.TASK_CODE AS task_code
FROM AUD_TASK_ATTEMPTS AS a
JOIN AUD_TASK_RUN_LOG AS tr
  ON tr.TASK_RUN_ID = a.TASK_RUN_ID
JOIN AUD_PIPELINES_RUN_LOG AS r
  ON r.PIPELINE_RUN_ID = tr.PIPELINE_RUN_ID
JOIN CFG_PIPELINES AS p
  ON p.PIPELINE_ID = r.PIPELINE_ID
JOIN CFG_TASKS AS t
  ON t.TASK_ID = tr.TASK_ID
WHERE
  p.PROJECT_ID = :project_id
  AND a.LOG_REMOVED_AT IS NULL
  AND NOT a.STATUS IN ('QUEUED', 'CLAIMED', 'RUNNING')
  AND a.ENDED_AT < :cutoff
  AND r.STATUS IN ('SUCCESS', 'FAILED', 'SKIPPED', 'CANCELLED')
  AND (
    NOT a.LOG_PATH IS NULL
    OR NOT a.TASK_LOG IS NULL
    OR EXISTS(
      SELECT
        1
      FROM AUD_ATTEMPT_LOG_CHUNKS AS c
      WHERE
        c.ATTEMPT_ID = a.ATTEMPT_ID
      LIMIT 1
      OFFSET 0
    )
  )
ORDER BY
  a.ENDED_AT,
  a.ATTEMPT_ID
LIMIT 10000
