SELECT t.TASK_ID AS task_id
FROM CFG_TASKS t JOIN CFG_PIPELINES r ON r.PIPELINE_ID=t.PIPELINE_ID
JOIN CFG_TASK_PARAMETERS a ON a.TASK_ID=t.TASK_ID
WHERE t.HANDLER='SQL' AND t.ACTIVE_FLAG='Y' AND r.ACTIVE_FLAG='Y'
  AND a.ACTIVE_FLAG='Y' AND a.PARAMETER_NAME='SQL_ACTION'
  AND a.PARAMETER_VALUE IN ('SCD1_MERGE','SCD2_MERGE')
