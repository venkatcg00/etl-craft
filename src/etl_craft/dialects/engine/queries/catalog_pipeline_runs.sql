-- The latest :limit runs of every active pipeline, newest first.
SELECT p.PIPELINE_CODE AS pipeline_code, r.PIPELINE_RUN_ID AS pipeline_run_id,
       r.BUNDLE_ID AS bundle_id, r.METADATA_VERSION AS metadata_version,
       r.STATUS AS status,
       CASE WHEN r.OUTPUT_REVISION > 1 OR r.REPAIR_PENDING = 'Y' THEN 'REPAIR'
            WHEN r.BACKFILL = 'Y' THEN 'BACKFILL'
            WHEN r.TRIGGER_KIND = 'SCHEDULE' THEN 'SCHEDULED' ELSE 'OTHER' END AS run_kind, r.RUN_DATE AS run_date, (r.BACKFILL = 'Y') AS backfill,
       r.START_DATE AS "start", r.END_DATE AS "end", r.SLA_STATUS AS sla_status, r.STARTED_BY AS started_by,
       r.STARTED_BY_KIND AS started_by_kind, r.ENDED_BY AS ended_by,
       r.ENDED_BY_KIND AS ended_by_kind
FROM (
    SELECT PIPELINE_ID, PIPELINE_RUN_ID, BUNDLE_ID, METADATA_VERSION, STATUS, RUN_DATE, BACKFILL, START_DATE, END_DATE,
           OUTPUT_REVISION, REPAIR_PENDING, TRIGGER_KIND, SLA_STATUS, STARTED_BY, STARTED_BY_KIND, ENDED_BY, ENDED_BY_KIND,
           ROW_NUMBER() OVER (PARTITION BY PIPELINE_ID ORDER BY PIPELINE_RUN_ID DESC) AS rn
    FROM AUD_PIPELINES_RUN_LOG
    WHERE PIPELINE_ID IN (SELECT PIPELINE_ID FROM CFG_PIPELINES WHERE ACTIVE_FLAG = 'Y')
) r
JOIN CFG_PIPELINES p ON p.PIPELINE_ID = r.PIPELINE_ID
WHERE r.rn <= :limit AND p.ACTIVE_FLAG = 'Y' AND p.PROJECT_ID=:project_id
ORDER BY p.PIPELINE_CODE, r.PIPELINE_RUN_ID DESC
