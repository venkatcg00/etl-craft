-- Read active definitions and their metadata revision without loading ended runs.
SELECT p.PIPELINE_ID AS pipeline_id, r.PIPELINE_RUN_ID AS pipeline_run_id,
       p.PIPELINE_CODE AS pipeline_code, r.BACKFILL AS backfill,
       r.METADATA_SNAPSHOT AS metadata_snapshot,r.METADATA_VERSION AS metadata_version
FROM AUD_PIPELINES_RUN_LOG r JOIN CFG_PIPELINES p ON p.PIPELINE_ID = r.PIPELINE_ID
WHERE r.TASK_SELECTION IS NULL AND (
    r.STATUS = 'IN-PROGRESS' OR (r.STATUS = 'QUEUED'
    AND NOT EXISTS (SELECT 1 FROM AUD_PIPELINES_RUN_LOG sibling
                    WHERE sibling.PIPELINE_ID=p.PIPELINE_ID AND sibling.STATUS='IN-PROGRESS' AND sibling.EXCLUSIVE_RUN='Y')
    AND r.PIPELINE_RUN_ID = (SELECT MIN(q.PIPELINE_RUN_ID) FROM AUD_PIPELINES_RUN_LOG q
                            WHERE q.PIPELINE_ID=p.PIPELINE_ID AND q.STATUS='QUEUED'))
)
AND (NOT EXISTS (
    SELECT 1 FROM AUD_PIPELINE_PAUSES a WHERE a.PIPELINE_ID = p.PIPELINE_ID
    AND a.RESUMED_AT IS NULL
) OR EXISTS (SELECT 1 FROM AUD_CONTROL_REQUESTS permission
WHERE permission.PIPELINE_RUN_ID=r.PIPELINE_RUN_ID AND permission.ACTION='RUN_PAUSED'
AND permission.STATUS='COMPLETED')
)
ORDER BY r.PIPELINE_RUN_ID
