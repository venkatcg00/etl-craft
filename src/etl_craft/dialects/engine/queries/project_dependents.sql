SELECT DISTINCT project.PROJECT_CODE AS project_code,p.PROJECT_ID AS project_id,
p.PIPELINE_CODE AS pipeline_code
FROM CFG_PIPELINE_DEPENDENCY d
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=d.PIPELINE_ID
JOIN CFG_PIPELINES u ON u.PIPELINE_ID=d.DEPENDS_ON_PIPELINE_ID
JOIN CFG_PROJECTS project ON project.PROJECT_ID=p.PROJECT_ID
WHERE d.ACTIVE_FLAG='Y' AND p.ACTIVE_FLAG='Y' AND project.ACTIVE_FLAG='Y'
AND u.PROJECT_ID=:project_id AND u.PIPELINE_CODE=:pipeline_code AND p.PROJECT_ID<>:project_id
ORDER BY project.PROJECT_CODE,p.PIPELINE_CODE
