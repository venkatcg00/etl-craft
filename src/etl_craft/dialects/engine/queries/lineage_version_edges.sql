SELECT e.LINEAGE_VERSION_ID AS lineage_version_id, e.TASK_ID AS task_id, p.PIPELINE_CODE || '.' || t.TASK_CODE AS task, v.TARGET_CATALOG_NAME AS target_catalog_name, v.TARGET_SCHEMA_NAME AS target_schema_name, v.TARGET_TABLE_NAME AS target_table_name, e.TARGET_COLUMN AS target_column, e.SOURCE_CATALOG_NAME AS source_catalog_name, e.SOURCE_SCHEMA_NAME AS source_schema_name, e.SOURCE_TABLE_NAME AS source_table_name, e.SOURCE_COLUMN AS source_column, e.TRANSFORMATION AS transformation
FROM AUD_LINEAGE_VERSION_EDGES e
JOIN AUD_LINEAGE_VERSIONS v ON v.LINEAGE_VERSION_ID=e.LINEAGE_VERSION_ID
JOIN CFG_TASKS t ON t.TASK_ID=e.TASK_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=t.PIPELINE_ID
WHERE e.LINEAGE_VERSION_ID=COALESCE(:version_id,e.LINEAGE_VERSION_ID)
ORDER BY e.LINEAGE_VERSION_EDGE_ID
