-- Holds still in force on the project's queued and running runs, newest first.
SELECT c.CONTROL_ID AS control_id, c.PIPELINE_RUN_ID AS pipeline_run_id,
       p.PIPELINE_CODE AS pipeline_code, t.TASK_CODE AS task_code,
       c.REQUESTED_BY AS requested_by, c.REASON AS reason, c.REQUESTED_AT AS requested_at
FROM AUD_PIPELINES_RUN_LOG r
JOIN CFG_PIPELINES p ON p.PIPELINE_ID = r.PIPELINE_ID AND p.PROJECT_ID = :project_id
JOIN AUD_CONTROL_REQUESTS c ON c.PIPELINE_RUN_ID = r.PIPELINE_RUN_ID AND c.ACTION = 'HOLD'
LEFT JOIN CFG_TASKS t ON t.TASK_ID = c.TASK_ID
WHERE r.STATUS IN ('QUEUED', 'IN-PROGRESS')
AND NOT EXISTS (SELECT 1 FROM AUD_CONTROL_REQUESTS newer
    WHERE newer.PIPELINE_RUN_ID = c.PIPELINE_RUN_ID AND newer.CONTROL_ID > c.CONTROL_ID
    AND newer.ACTION IN ('HOLD', 'RELEASE', 'STOP', 'ABORT', 'RECOVER')
    AND (newer.TASK_ID = c.TASK_ID OR (newer.TASK_ID IS NULL AND c.TASK_ID IS NULL)))
ORDER BY c.CONTROL_ID DESC
LIMIT 200
