WITH definition AS (
SELECT COALESCE(MAX(CASE WHEN v.PARAMETER_NAME='POOL' THEN v.PARAMETER_VALUE END),'default') AS pool,
p.PRIORITY AS priority,
CASE WHEN t.HANDLER='EVENT_WAIT' THEN '0' ELSE COALESCE(
 MAX(CASE WHEN v.PARAMETER_NAME='CPU_REQUEST' THEN v.PARAMETER_VALUE END),
 CAST(CASE WHEN :kind='python' THEN :python_cpu ELSE :warehouse_cpu END AS varchar)) END AS cpu,
CASE WHEN t.HANDLER='EVENT_WAIT' THEN '0' ELSE COALESCE(
 MAX(CASE WHEN v.PARAMETER_NAME='MEMORY_REQUEST_MB' THEN v.PARAMETER_VALUE END),
 CAST(CASE WHEN :kind='python' THEN :python_memory_mb ELSE :warehouse_memory_mb END AS varchar)) END AS memory_mb
FROM AUD_TASK_ATTEMPTS a JOIN AUD_TASK_RUN_LOG r ON r.TASK_RUN_ID=a.TASK_RUN_ID
JOIN CFG_TASKS t ON t.TASK_ID=r.TASK_ID JOIN CFG_PIPELINES p ON p.PIPELINE_ID=t.PIPELINE_ID
LEFT JOIN CFG_TASK_PARAMETERS v ON v.TASK_ID=t.TASK_ID AND v.ACTIVE_FLAG='Y'
WHERE a.ATTEMPT_ID=:attempt_id GROUP BY p.PRIORITY,t.HANDLER)
UPDATE AUD_TASK_ATTEMPTS SET POOL=(SELECT pool FROM definition), SLOT_KIND=:kind,
PRIORITY=(SELECT priority FROM definition), FORCE_FLAG=:force, RERUN_FLAG=:rerun,
ERROR_MESSAGE=COALESCE(:reason,(SELECT 'QUEUED in pool ' || pool || ': needs ' || memory_mb
 || ' MB and ' || cpu || ' CPU; waiting for resources or a free ' || :kind || ' slot' FROM definition))
WHERE ATTEMPT_ID=:attempt_id AND STATUS='QUEUED' AND OWNER_ID IS NULL
