SELECT c.CALENDAR_CODE AS calendar_code, c.WEEKEND_DAYS AS weekend_days,
       (SELECT MAX(h.HOLIDAY_DATE) FROM CFG_CALENDAR_HOLIDAYS h WHERE h.CALENDAR_ID=c.CALENDAR_ID AND h.ACTIVE_FLAG='Y') AS last_holiday
FROM CFG_CALENDARS c WHERE c.ACTIVE_FLAG='Y' AND c.PROJECT_ID=:project_id
ORDER BY c.CALENDAR_ID
