 ACTIVE_FLAG AS active_flag,RUN_SCHEDULE AS run_schedule,
 (SELECT MIN(t.TASK_CODE) FROM CFG_TASKS t WHERE t.PIPELINE_ID=CFG_PIPELINES.PIPELINE_ID
 AND t.HANDLER='FILE_VALIDATION' AND t.ACTIVE_FLAG='Y') AS validation_task FROM CFG_PIPELINES WHERE PIPELINE_ID=:pipeline_id
