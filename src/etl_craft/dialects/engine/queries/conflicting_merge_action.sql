SELECT DISTINCT upper(trim(a.PARAMETER_VALUE)) AS sql_action
FROM CFG_TASKS t
JOIN CFG_PIPELINES p ON p.PIPELINE_ID = t.PIPELINE_ID AND p.ACTIVE_FLAG = 'Y'
JOIN CFG_TASKS origin ON origin.TASK_ID=:task_id
JOIN CFG_TABLES o ON o.TABLE_ID=t.TARGET_TABLE_ID AND o.ACTIVE_FLAG='Y'
JOIN CFG_TASK_PARAMETERS a ON a.TASK_ID = t.TASK_ID
  AND a.PARAMETER_NAME = 'SQL_ACTION' AND a.ACTIVE_FLAG = 'Y'
WHERE t.ACTIVE_FLAG = 'Y' AND t.HANDLER = 'SQL' AND t.TASK_ID <> :task_id
  AND t.TARGET_TABLE_ID=origin.TARGET_TABLE_ID
  AND t.TARGET_ACTIVE_FLAG='Y' AND origin.TARGET_ACTIVE_FLAG='Y'
  AND upper(trim(a.PARAMETER_VALUE)) IN ('SCD1_MERGE', 'SCD2_MERGE')
  AND upper(trim(a.PARAMETER_VALUE)) <> :sql_action
LIMIT 1
