SELECT t.TASK_ID AS task_id, t.TASK_CODE AS task_code, t.TASK_TYPE AS task_type,
       p.PIPELINE_CODE AS pipeline_code, target.PARAMETER_VALUE AS target_code, 1 AS project_id
FROM CFG_TASKS t JOIN CFG_PIPELINES p ON p.PIPELINE_ID=t.PIPELINE_ID
LEFT JOIN CFG_TASK_PARAMETERS target ON target.TASK_ID=t.TASK_ID AND target.PARAMETER_NAME='TRIGGER_PIPELINE_CODE' AND target.ACTIVE_FLAG='Y'
WHERE t.HANDLER='RUN_PIPELINE' AND t.ACTIVE_FLAG='Y' AND p.ACTIVE_FLAG='Y'
ORDER BY p.PIPELINE_CODE,t.TASK_CODE
