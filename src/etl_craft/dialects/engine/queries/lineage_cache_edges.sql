SELECT c.TASK_ID AS task_id, c.TARGET_CATALOG_NAME AS target_catalog_name, c.TARGET_SCHEMA_NAME AS target_schema_name, c.TARGET_TABLE_NAME AS target_table_name, c.TARGET_COLUMN AS target_column, c.SOURCE_CATALOG_NAME AS source_catalog_name, c.SOURCE_SCHEMA_NAME AS source_schema_name, c.SOURCE_TABLE_NAME AS source_table_name, c.SOURCE_COLUMN AS source_column, c.TRANSFORMATION AS transformation
FROM AUD_COLUMN_LINEAGE c
JOIN CFG_TASKS t ON t.TASK_ID=c.TASK_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=t.PIPELINE_ID
JOIN CFG_TABLES target ON target.TABLE_ID=t.TARGET_TABLE_ID
WHERE t.ACTIVE_FLAG='Y' AND p.ACTIVE_FLAG='Y' AND t.HANDLER='SQL' AND t.TARGET_ACTIVE_FLAG='Y'
AND NOT EXISTS (SELECT 1 FROM CFG_TASK_PARAMETERS param WHERE param.TASK_ID=t.TASK_ID AND param.PARAMETER_NAME='SQL_ACTION' AND UPPER(param.PARAMETER_VALUE)='DROP_TABLE' AND param.ACTIVE_FLAG='Y')
AND LOWER(target.SCHEMA_NAME)=c.TARGET_SCHEMA_NAME AND LOWER(target.TABLE_NAME)=c.TARGET_TABLE_NAME
AND COALESCE(LOWER(target.CATALOG_NAME),:catalog,'')=COALESCE(c.TARGET_CATALOG_NAME,'')
ORDER BY c.COLUMN_LINEAGE_ID
