SELECT
  COUNT(*) AS count
FROM AUD_PIPELINE_PAUSES AS t
WHERE
  (
    EXISTS(
      SELECT
        1
      FROM CFG_PIPELINES AS p
      WHERE
        p.PIPELINE_ID = t.PIPELINE_ID AND p.PROJECT_ID = :project_id
      LIMIT 1
      OFFSET 0
    )
  )
  AND COALESCE(t.RESUMED_AT,t.EXPIRES_AT) < :cutoff
      AND NOT EXISTS (SELECT 1 FROM AUD_RUN_INTERVENTIONS i
          WHERE i.ITEM_KEY=CAST(t.PIPELINE_PAUSE_ID AS varchar)
          AND i.ACTION IN ('PAUSE_ADMISSION','PAUSE_APPLIED'))
