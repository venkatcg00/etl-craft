WITH children AS (
    SELECT PIPELINE_RUN_ID AS child_run_id FROM AUD_PIPELINES_RUN_LOG
    WHERE PIPELINE_RUN_ID IN :run_ids
    UNION
    SELECT r.PIPELINE_RUN_ID AS child_run_id FROM AUD_TASK_RUN_LOG t
    JOIN AUD_PIPELINES_RUN_LOG r ON r.TRIGGERED_BY_TASK_RUN_ID=t.TASK_RUN_ID
    WHERE t.PIPELINE_RUN_ID IN :run_ids
)
SELECT r.PIPELINE_RUN_ID AS child_run_id, p.PIPELINE_CODE AS child_code,
       t.TASK_RUN_ID AS task_run_id, t.PIPELINE_RUN_ID AS parent_run_id,
       parent.PIPELINE_CODE AS parent_code, task.TASK_CODE AS task_code
FROM children c JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=c.child_run_id
JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID=r.TRIGGERED_BY_TASK_RUN_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
JOIN AUD_PIPELINES_RUN_LOG parent_run ON parent_run.PIPELINE_RUN_ID=t.PIPELINE_RUN_ID
JOIN CFG_PIPELINES parent ON parent.PIPELINE_ID=parent_run.PIPELINE_ID
JOIN CFG_TASKS task ON task.TASK_ID=t.TASK_ID
WHERE NOT :project_only OR (p.PROJECT_ID=:project_id AND parent.PROJECT_ID=:project_id)
ORDER BY r.PIPELINE_RUN_ID
