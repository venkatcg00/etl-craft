SELECT r.PIPELINE_RUN_ID AS child_run_id, p.PIPELINE_CODE AS child_code,
       t.TASK_RUN_ID AS task_run_id, t.PIPELINE_RUN_ID AS parent_run_id,
       parent.PIPELINE_CODE AS parent_code, task.TASK_CODE AS task_code
FROM AUD_PIPELINES_RUN_LOG r JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID=r.TRIGGERED_BY_TASK_RUN_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
JOIN AUD_PIPELINES_RUN_LOG parent_run ON parent_run.PIPELINE_RUN_ID=t.PIPELINE_RUN_ID
JOIN CFG_PIPELINES parent ON parent.PIPELINE_ID=parent_run.PIPELINE_ID
JOIN CFG_TASKS task ON task.TASK_ID=t.TASK_ID
WHERE r.PIPELINE_RUN_ID IN :run_ids OR t.PIPELINE_RUN_ID IN :run_ids
ORDER BY r.PIPELINE_RUN_ID
