SELECT a.PIPELINE_PAUSE_ID AS pause_id,a.PIPELINE_ID AS pipeline_id,
p.PIPELINE_CODE AS pipeline_code,t.TASK_CODE AS task_code,
a.RESUMED_AT AS resumed_at,a.RESUMED_BY AS actor,a.RESUME_REASON AS reason
FROM AUD_PIPELINE_PAUSES a JOIN CFG_PIPELINES p ON p.PIPELINE_ID=a.PIPELINE_ID
LEFT JOIN CFG_TASKS t ON t.TASK_ID=a.TASK_ID
WHERE p.PROJECT_ID=:project_id AND a.RESUMED_AT IS NOT NULL
AND (:pipeline_id IS NULL OR a.PIPELINE_ID=:pipeline_id)
AND (:since IS NULL OR a.RESUMED_AT>=:since)
ORDER BY a.PIPELINE_PAUSE_ID DESC
