UPDATE AUD_GATE_WAITS SET NEXT_CHECK_AT=:now
WHERE WAIT_KIND='PIPELINE_RUN' AND NEXT_CHECK_AT IS NOT NULL AND EXISTS (
SELECT 1 FROM AUD_PIPELINES_RUN_LOG r JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID=r.TRIGGERED_BY_TASK_RUN_ID
WHERE r.PIPELINE_RUN_ID=:child_run_id AND t.PIPELINE_RUN_ID=AUD_GATE_WAITS.PIPELINE_RUN_ID
AND t.TASK_ID=AUD_GATE_WAITS.TASK_ID)
