SELECT p.PROJECT_ID AS project_id,a.POOL AS pool,a.QUEUED_AT AS queued_at,
RESERVED_CPU AS reserved_cpu, RESERVED_MEMORY_MB AS reserved_memory_mb, a.ATTEMPT_ID AS attempt_id, a.STATUS AS status, a.SLOT_KIND AS slot_kind,
a.OWNER_ID AS owner_id, a.CANCEL_REQUESTED_AT AS cancel_requested_at,
a.LEASE_EXPIRES_AT AS lease_expires_at, t.TASK_RUN_ID AS task_run_id
FROM AUD_TASK_ATTEMPTS a JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID=a.TASK_RUN_ID
JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=t.PIPELINE_RUN_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
WHERE (CAST(:owner AS varchar) IS NULL OR a.OWNER_ID=:owner)
AND a.STATUS IN ('QUEUED','CLAIMED','RUNNING')
