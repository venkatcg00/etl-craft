SELECT 'pipelines.csv' AS file,
(SELECT p.PIPELINE_CODE AS code FROM CFG_PIPELINES p
 WHERE p.PIPELINE_ID=r.PIPELINE_ID LIMIT 1 OFFSET 0) AS pipeline_code,
(SELECT h.PIPELINE_CODE AS code FROM AUD_CFG_PIPELINES_HISTORY h
 WHERE h.PIPELINE_ID=r.PIPELINE_ID AND h.CHANGE_ID<r.CHANGE_ID
 ORDER BY h.CHANGE_ID DESC LIMIT 1 OFFSET 0) AS old_code,r.PIPELINE_CODE AS new_code,r.ACTOR AS actor,r.VALID_FROM AS renamed_at
FROM AUD_CFG_PIPELINES_HISTORY r WHERE r.MIGRATION='rename' AND r.PROJECT_ID=:project_id
AND (SELECT h.PIPELINE_CODE AS code FROM AUD_CFG_PIPELINES_HISTORY h
 WHERE h.PIPELINE_ID=r.PIPELINE_ID AND h.CHANGE_ID<r.CHANGE_ID
 ORDER BY h.CHANGE_ID DESC LIMIT 1 OFFSET 0)<>r.PIPELINE_CODE
UNION ALL
SELECT 'tasks.csv' AS file,
(SELECT p.PIPELINE_CODE AS code FROM CFG_PIPELINES p
 WHERE p.PIPELINE_ID=r.PIPELINE_ID LIMIT 1 OFFSET 0) AS pipeline_code,
(SELECT h.TASK_CODE AS code FROM AUD_CFG_TASKS_HISTORY h
 WHERE h.TASK_ID=r.TASK_ID AND h.CHANGE_ID<r.CHANGE_ID
 ORDER BY h.CHANGE_ID DESC LIMIT 1 OFFSET 0) AS old_code,r.TASK_CODE AS new_code,r.ACTOR AS actor,r.VALID_FROM AS renamed_at
FROM AUD_CFG_TASKS_HISTORY r WHERE r.MIGRATION='rename' AND EXISTS (SELECT 1 AS permitted FROM CFG_PIPELINES p
 WHERE p.PIPELINE_ID=r.PIPELINE_ID AND p.PROJECT_ID=:project_id LIMIT 1 OFFSET 0)
AND (SELECT h.TASK_CODE AS code FROM AUD_CFG_TASKS_HISTORY h
 WHERE h.TASK_ID=r.TASK_ID AND h.CHANGE_ID<r.CHANGE_ID
 ORDER BY h.CHANGE_ID DESC LIMIT 1 OFFSET 0)<>r.TASK_CODE
