SELECT i.TASK_RUN_ID AS task_run_id, COUNT(*) AS total,
SUM(CASE WHEN i.STATUS IN ('SUCCESS','SKIPPED') AND i.ROW_COUNT IS NULL THEN 1 ELSE 0 END) AS unmeasured,
SUM(CASE WHEN i.STATUS IN ('SUCCESS','SKIPPED') AND i.ROW_COUNT IS NOT NULL THEN 1 ELSE 0 END) AS measured,
SUM(CASE WHEN i.STATUS IN ('SUCCESS','SKIPPED') THEN 1 ELSE 0 END) AS done,
SUM(CASE WHEN i.STATUS='SKIPPED' THEN 1 ELSE 0 END) AS skipped,
SUM(CASE WHEN i.STATUS IN ('FAILED','CANCELLED')
 OR (i.STATUS='RUNNING' AND a.STATUS NOT IN ('CLAIMED','RUNNING'))
 OR (i.STATUS='QUEUED' AND a.STATUS='CANCELLED')
 OR (i.STATUS='CANCEL_REQUESTED' AND a.STATUS NOT IN ('CLAIMED','RUNNING','LOST'))
 THEN 1 ELSE 0 END) AS failed
FROM AUD_TASK_ITEMS i JOIN AUD_TASK_ATTEMPTS a ON a.ATTEMPT_ID=i.ATTEMPT_ID
WHERE i.TASK_RUN_ID IN (SELECT CAST(value AS bigint) AS task_run_id FROM json_each(:task_run_ids))
AND NOT EXISTS (SELECT 1 FROM AUD_TASK_ITEMS n WHERE n.TASK_RUN_ID=i.TASK_RUN_ID
AND n.ITEM_KEY=i.ITEM_KEY AND n.ITEM_RECORD_ID>i.ITEM_RECORD_ID)
GROUP BY i.TASK_RUN_ID
