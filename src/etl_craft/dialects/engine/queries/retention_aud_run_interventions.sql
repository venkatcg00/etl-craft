DELETE FROM AUD_RUN_INTERVENTIONS WHERE INTERVENTION_ID IN (
SELECT t.INTERVENTION_ID AS row_id FROM AUD_RUN_INTERVENTIONS t WHERE (EXISTS (SELECT 1 FROM AUD_PIPELINES_RUN_LOG r JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID WHERE p.PROJECT_ID=:project_id AND r.STATUS IN ('SUCCESS','FAILED','SKIPPED','CANCELLED') AND r.END_DATE < :cutoff AND r.PIPELINE_RUN_ID=t.PIPELINE_RUN_ID)) AND t.REQUESTED_AT < :cutoff
ORDER BY t.INTERVENTION_ID LIMIT 10000
)
