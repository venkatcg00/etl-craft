SELECT 'project' AS kind,PROJECT_CODE AS identity FROM CFG_PROJECTS
WHERE ACTIVE_FLAG='Y' AND DEFAULT_POOL=:pool
UNION ALL
SELECT 'task' AS kind,p.PROJECT_CODE || '/' || l.PIPELINE_CODE || '.' || t.TASK_CODE AS identity
FROM CFG_TASKS t JOIN CFG_PIPELINES l ON l.PIPELINE_ID=t.PIPELINE_ID
JOIN CFG_PROJECTS p ON p.PROJECT_ID=l.PROJECT_ID
JOIN CFG_TASK_PARAMETERS x ON x.TASK_ID=t.TASK_ID
WHERE t.ACTIVE_FLAG='Y' AND x.ACTIVE_FLAG='Y' AND x.PARAMETER_NAME='POOL'
AND x.PARAMETER_VALUE=:pool
