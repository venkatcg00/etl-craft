SELECT a.ATTEMPT_ID AS attempt_id, a.LOG_PATH AS log_path,
a.LOG_REMOVED_AT AS log_removed_at, a.STATUS AS status, a.OWNER_ID AS owner_id,
a.TASK_RUN_ID AS task_run_id, a.ATTEMPT_NUMBER AS attempt_number,
r.PIPELINE_RUN_ID AS pipeline_run_id, p.PROJECT_ID AS project_id,
p.PIPELINE_CODE AS pipeline_code, t.TASK_CODE AS task_code
FROM AUD_TASK_ATTEMPTS a
JOIN AUD_TASK_RUN_LOG tr ON tr.TASK_RUN_ID=a.TASK_RUN_ID
JOIN AUD_PIPELINES_RUN_LOG r ON r.PIPELINE_RUN_ID=tr.PIPELINE_RUN_ID
JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
JOIN CFG_TASKS t ON t.TASK_ID=tr.TASK_ID
WHERE a.ATTEMPT_ID=:attempt_id
