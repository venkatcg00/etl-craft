-- Extend pipeline admission and preserve immutable handed-off attempt evidence.
ALTER TABLE CFG_TASKS DROP CONSTRAINT ck_tasks_handler;
ALTER TABLE CFG_TASKS ADD CONSTRAINT ck_tasks_handler CHECK (HANDLER IN ('PYTHON','SQL','BUSINESS_RULES','EMAIL_ALERT','EVENT_WAIT','RUN_PIPELINE'));
ALTER TABLE AUD_PIPELINES_RUN_LOG DROP CONSTRAINT ck_pipeline_run_trigger_kind;
ALTER TABLE AUD_PIPELINES_RUN_LOG ADD CONSTRAINT ck_pipeline_run_trigger_kind CHECK (TRIGGER_KIND IN ('SCHEDULE','MANUAL','BACKFILL','ORCHESTRATOR','STAND_IN','PIPELINE_TASK'));
ALTER TABLE AUD_TASK_ATTEMPTS DROP CONSTRAINT ck_attempt_status;
ALTER TABLE AUD_TASK_ATTEMPTS ADD CONSTRAINT ck_attempt_status CHECK (STATUS IN ('QUEUED','CLAIMED','RUNNING','SUCCESS','FAILED','TIMED_OUT','CANCELLED','LOST','HANDED_OFF'));
ALTER TABLE AUD_GATE_WAITS DROP CONSTRAINT ck_gate_wait_deadline;
ALTER TABLE AUD_GATE_WAITS ADD CONSTRAINT ck_gate_wait_deadline CHECK (WAIT_KIND IN ('EVENT','PIPELINE_RUN') OR WAIT_UNTIL IS NOT NULL);
ALTER TABLE AUD_GATE_WAITS DROP CONSTRAINT aud_gate_waits_wait_kind_check;
ALTER TABLE AUD_GATE_WAITS ADD CONSTRAINT aud_gate_waits_wait_kind_check CHECK (WAIT_KIND IN ('DEPENDENCY','EVENT','PIPELINE_RUN'));
ALTER TABLE AUD_TASK_RUN_LOG ADD COLUMN TRIGGER_GENERATION INT NOT NULL DEFAULT 0 CHECK (TRIGGER_GENERATION >= 0);
ALTER TABLE AUD_PIPELINES_RUN_LOG ADD COLUMN TRIGGERED_BY_TASK_RUN_ID BIGINT CONSTRAINT fk_run_trigger_task REFERENCES AUD_TASK_RUN_LOG(TASK_RUN_ID);
CREATE INDEX ix_run_trigger_task ON AUD_PIPELINES_RUN_LOG (TRIGGERED_BY_TASK_RUN_ID);

CREATE INDEX ix_trigger_wait_active ON AUD_GATE_WAITS (PIPELINE_RUN_ID, TASK_ID) WHERE WAIT_KIND='PIPELINE_RUN' AND NEXT_CHECK_AT IS NOT NULL;
