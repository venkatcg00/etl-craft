-- Stable deployment identity namespaces archive rows across Engine DBs.
CREATE TABLE AUD_ENGINE_IDENTITY (
    IDENTITY_ID INTEGER PRIMARY KEY CHECK (IDENTITY_ID=1),
    ENGINE_ID VARCHAR(32) NOT NULL
);
INSERT INTO AUD_ENGINE_IDENTITY (IDENTITY_ID,ENGINE_ID) VALUES (1,replace(gen_random_uuid()::text,'-',''));
-- One admitted archive snapshot per project survives remote commit acknowledgement loss.
CREATE TABLE AUD_RETENTION_ARCHIVES (
    PROJECT_ID BIGINT PRIMARY KEY REFERENCES CFG_PROJECTS(PROJECT_ID),
    BATCH_ID VARCHAR(32) NOT NULL,
    DESTINATION VARCHAR(64) NOT NULL,
    SCHEMA_NAME VARCHAR NOT NULL,
    BODY TEXT NOT NULL,
    CREATED_AT TIMESTAMPTZ NOT NULL
);
CREATE TRIGGER trg_actor_guard_aud_engine_identity BEFORE INSERT OR UPDATE OR DELETE ON AUD_ENGINE_IDENTITY FOR EACH ROW EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_truncate_aud_engine_identity BEFORE TRUNCATE ON AUD_ENGINE_IDENTITY FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_actor_guard_aud_retention_archives BEFORE INSERT OR UPDATE OR DELETE ON AUD_RETENTION_ARCHIVES FOR EACH ROW EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_truncate_aud_retention_archives BEFORE TRUNCATE ON AUD_RETENTION_ARCHIVES FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_guard();
