-- Replace derived task cache; table lineage history begins with the next computation.
DROP TABLE AUD_COLUMN_LINEAGE;
CREATE TABLE AUD_COLUMN_LINEAGE (
    COLUMN_LINEAGE_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TASK_ID BIGINT NOT NULL REFERENCES CFG_TASKS(TASK_ID),
    SOURCE_SQL_HASH VARCHAR NOT NULL,
    TARGET_CATALOG_NAME VARCHAR,
    TARGET_SCHEMA_NAME VARCHAR NOT NULL,
    TARGET_TABLE_NAME VARCHAR NOT NULL,
    TARGET_COLUMN VARCHAR NOT NULL,
    SOURCE_CATALOG_NAME VARCHAR,
    SOURCE_SCHEMA_NAME VARCHAR,
    SOURCE_TABLE_NAME VARCHAR,
    SOURCE_COLUMN VARCHAR,
    TRANSFORMATION VARCHAR,
    COMPUTED_AT TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE AUD_COLUMN_LINEAGE IS 'Derived SQL task lineage cache keyed by SQL, parser version and source schemas.';
CREATE INDEX ix_column_lineage_task ON AUD_COLUMN_LINEAGE (TASK_ID, SOURCE_SQL_HASH);
CREATE INDEX ix_column_lineage_target ON AUD_COLUMN_LINEAGE (TARGET_CATALOG_NAME, TARGET_SCHEMA_NAME, TARGET_TABLE_NAME, TARGET_COLUMN);
CREATE INDEX ix_column_lineage_source ON AUD_COLUMN_LINEAGE (SOURCE_CATALOG_NAME, SOURCE_SCHEMA_NAME, SOURCE_TABLE_NAME, SOURCE_COLUMN);
-- Table lineage fingerprints and validity intervals, retained when edges change.
CREATE TABLE AUD_LINEAGE_VERSIONS (
    LINEAGE_VERSION_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TARGET_CATALOG_NAME VARCHAR,
    TARGET_SCHEMA_NAME VARCHAR NOT NULL,
    TARGET_TABLE_NAME VARCHAR NOT NULL,
    VERSION_NUMBER INTEGER NOT NULL CHECK (VERSION_NUMBER > 0),
    EDGES_HASH VARCHAR(64) NOT NULL,
    VALID_FROM TIMESTAMPTZ NOT NULL,
    VALID_TO TIMESTAMPTZ NOT NULL,
    CURRENT_FLAG VARCHAR(1) NOT NULL CHECK (CURRENT_FLAG IN ('Y','N')),
    CHECK (VALID_TO >= VALID_FROM)
);
COMMENT ON TABLE AUD_LINEAGE_VERSIONS IS 'Append-only per-target table lineage versions and validity intervals.';
CREATE UNIQUE INDEX ux_lineage_version_number ON AUD_LINEAGE_VERSIONS (COALESCE(TARGET_CATALOG_NAME,''), TARGET_SCHEMA_NAME, TARGET_TABLE_NAME, VERSION_NUMBER);
CREATE UNIQUE INDEX ux_lineage_version_current ON AUD_LINEAGE_VERSIONS (COALESCE(TARGET_CATALOG_NAME,''), TARGET_SCHEMA_NAME, TARGET_TABLE_NAME) WHERE CURRENT_FLAG='Y';
-- Recorded column sources and writing tasks belonging to a table lineage version.
CREATE TABLE AUD_LINEAGE_VERSION_EDGES (
    LINEAGE_VERSION_EDGE_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    LINEAGE_VERSION_ID BIGINT NOT NULL REFERENCES AUD_LINEAGE_VERSIONS(LINEAGE_VERSION_ID),
    TASK_ID BIGINT NOT NULL REFERENCES CFG_TASKS(TASK_ID),
    TARGET_COLUMN VARCHAR NOT NULL,
    SOURCE_CATALOG_NAME VARCHAR,
    SOURCE_SCHEMA_NAME VARCHAR,
    SOURCE_TABLE_NAME VARCHAR,
    SOURCE_COLUMN VARCHAR,
    TRANSFORMATION VARCHAR
);
COMMENT ON TABLE AUD_LINEAGE_VERSION_EDGES IS 'Recorded column sources and writing tasks for a table lineage version.';
CREATE INDEX ix_lineage_version_edges ON AUD_LINEAGE_VERSION_EDGES (LINEAGE_VERSION_ID);
CREATE TRIGGER trg_actor_guard_aud_column_lineage BEFORE INSERT OR UPDATE OR DELETE ON AUD_COLUMN_LINEAGE FOR EACH ROW EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_truncate_aud_column_lineage BEFORE TRUNCATE ON AUD_COLUMN_LINEAGE FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_actor_guard_aud_lineage_versions BEFORE INSERT OR UPDATE OR DELETE ON AUD_LINEAGE_VERSIONS FOR EACH ROW EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_truncate_aud_lineage_versions BEFORE TRUNCATE ON AUD_LINEAGE_VERSIONS FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_actor_guard_aud_lineage_version_edges BEFORE INSERT OR UPDATE OR DELETE ON AUD_LINEAGE_VERSION_EDGES FOR EACH ROW EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_truncate_aud_lineage_version_edges BEFORE TRUNCATE ON AUD_LINEAGE_VERSION_EDGES FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_guard();
CREATE FUNCTION etl_craft_lineage_history_guard() RETURNS trigger AS $$
BEGIN
    IF COALESCE(current_setting('etl_craft.actor', true), '') = '' THEN
        RAISE EXCEPTION USING MESSAGE = upper(TG_TABLE_NAME) || ' is written only by etl-craft; record lineage with etl-craft lineage';
    END IF;
    IF TG_TABLE_NAME = 'aud_lineage_versions' AND TG_OP = 'UPDATE' THEN
        IF OLD.current_flag='Y' AND NEW.current_flag='N' AND NEW.valid_to >= OLD.valid_from
           AND to_jsonb(NEW) - ARRAY['valid_to','current_flag'] = to_jsonb(OLD) - ARRAY['valid_to','current_flag'] THEN
            RETURN NEW;
        END IF;
    END IF;
    RAISE EXCEPTION USING MESSAGE = upper(TG_TABLE_NAME) || ' rejects ' || TG_OP || ': lineage history is append-only; only closing a current version is allowed; recompute with etl-craft lineage';
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_lineage_versions_immutable BEFORE UPDATE OR DELETE ON AUD_LINEAGE_VERSIONS FOR EACH ROW EXECUTE FUNCTION etl_craft_lineage_history_guard();
CREATE TRIGGER trg_lineage_versions_truncate BEFORE TRUNCATE ON AUD_LINEAGE_VERSIONS FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_lineage_history_guard();
CREATE TRIGGER trg_lineage_edges_immutable BEFORE UPDATE OR DELETE ON AUD_LINEAGE_VERSION_EDGES FOR EACH ROW EXECUTE FUNCTION etl_craft_lineage_history_guard();
CREATE TRIGGER trg_lineage_edges_truncate BEFORE TRUNCATE ON AUD_LINEAGE_VERSION_EDGES FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_lineage_history_guard();
