-- Live process connection reservations, retained after clean or expired ownership ends.
CREATE TABLE AUD_CONNECTION_RESERVATIONS (
    RESERVATION_ID VARCHAR(64) PRIMARY KEY,
    ROLE VARCHAR(16) NOT NULL CHECK (ROLE IN ('CONTROLLER','UI','RUN')),
    HOST VARCHAR NOT NULL,
    PID BIGINT NOT NULL,
    BIRTH_TIME DOUBLE PRECISION NOT NULL,
    POOL_CONNECTIONS INTEGER NOT NULL CHECK (POOL_CONNECTIONS > 0),
    SESSION_CONNECTIONS INTEGER NOT NULL CHECK (SESSION_CONNECTIONS >= 0),
    LOCAL_TASK_CONNECTIONS INTEGER NOT NULL CHECK (LOCAL_TASK_CONNECTIONS >= 0),
    BACKEND_PID INTEGER NOT NULL,
    BACKEND_STARTED_AT TIMESTAMPTZ NOT NULL,
    STARTED_AT TIMESTAMPTZ NOT NULL,
    HEARTBEAT_AT TIMESTAMPTZ NOT NULL,
    EXPIRES_AT TIMESTAMPTZ NOT NULL,
    STOPPED_AT TIMESTAMPTZ,
    ACTOR VARCHAR NOT NULL,
    ACTOR_KIND VARCHAR NOT NULL
);
CREATE INDEX ix_connection_reservations_active ON AUD_CONNECTION_RESERVATIONS (EXPIRES_AT) WHERE STOPPED_AT IS NULL;
CREATE TRIGGER trg_actor_guard_aud_connection_reservations BEFORE INSERT OR UPDATE OR DELETE ON AUD_CONNECTION_RESERVATIONS FOR EACH ROW EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_truncate_aud_connection_reservations BEFORE TRUNCATE ON AUD_CONNECTION_RESERVATIONS FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_guard();
