-- Repository definitions of external and script-landed table columns.
CREATE TABLE CFG_SOURCE_COLUMNS (
    SOURCE_COLUMN_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TABLE_NAME VARCHAR NOT NULL,
    COLUMN_NAME VARCHAR NOT NULL,
    DATA_TYPE VARCHAR NOT NULL,
    COLUMN_POSITION INTEGER NOT NULL CONSTRAINT ck_source_column_position CHECK (COLUMN_POSITION > 0),
    ACTIVE_FLAG VARCHAR NOT NULL DEFAULT 'Y' CONSTRAINT ck_source_column_active CHECK (ACTIVE_FLAG IN ('Y','N')),
    CREATED_BY VARCHAR,
    CREATE_DATE TIMESTAMPTZ,
    UPDATED_BY VARCHAR,
    UPDATED_DATE TIMESTAMPTZ
);
CREATE UNIQUE INDEX ux_source_column_active ON CFG_SOURCE_COLUMNS (lower(TABLE_NAME), lower(COLUMN_NAME)) WHERE ACTIVE_FLAG = 'Y';
CREATE UNIQUE INDEX ux_source_position_active ON CFG_SOURCE_COLUMNS (lower(TABLE_NAME), COLUMN_POSITION) WHERE ACTIVE_FLAG = 'Y';

-- Immutable versions of each source definition, with its actor and project migration.
CREATE TABLE AUD_CFG_SOURCE_COLUMNS_HISTORY (
    CHANGE_ID BIGINT PRIMARY KEY,
    VALID_FROM TIMESTAMPTZ NOT NULL,
    VALID_TO TIMESTAMPTZ NOT NULL,
    CURRENT_FLAG VARCHAR(1) NOT NULL,
    OPERATION VARCHAR NOT NULL,
    ACTOR VARCHAR NOT NULL,
    ACTOR_KIND VARCHAR NOT NULL,
    MIGRATION VARCHAR,
    SOURCE_COLUMN_ID BIGINT,
    TABLE_NAME VARCHAR,
    COLUMN_NAME VARCHAR,
    DATA_TYPE VARCHAR,
    COLUMN_POSITION INTEGER,
    ACTIVE_FLAG VARCHAR,
    CREATED_BY VARCHAR,
    CREATE_DATE TIMESTAMPTZ,
    UPDATED_BY VARCHAR,
    UPDATED_DATE TIMESTAMPTZ,
    CONSTRAINT ck_aud_cfg_source_columns_history_operation CHECK (OPERATION IN ('INSERT','UPDATE','DELETE')),
    CONSTRAINT ck_aud_cfg_source_columns_history_current CHECK (CURRENT_FLAG IN ('Y','N'))
);
CREATE INDEX ix_aud_cfg_source_columns_history_row ON AUD_CFG_SOURCE_COLUMNS_HISTORY (SOURCE_COLUMN_ID, CHANGE_ID);
CREATE INDEX ix_aud_cfg_source_columns_history_current ON AUD_CFG_SOURCE_COLUMNS_HISTORY (SOURCE_COLUMN_ID) WHERE CURRENT_FLAG = 'Y';
