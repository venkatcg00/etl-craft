-- Remove external scheduler parameters from current pipeline definitions.
UPDATE CFG_PIPELINES
SET PIPELINE_PARAMETERS = (PIPELINE_PARAMETERS::jsonb - ARRAY['CATCHUP', 'DEPENDS_ON_PAST', 'EMAIL_ON_FAILURE', 'RETRIES', 'RETRY_DELAY_MINUTES'])::json
WHERE PIPELINE_PARAMETERS IS NOT NULL AND (PIPELINE_PARAMETERS::jsonb ?| ARRAY['CATCHUP', 'DEPENDS_ON_PAST', 'EMAIL_ON_FAILURE', 'RETRIES', 'RETRY_DELAY_MINUTES']);
