ALTER TABLE CFG_PIPELINES ADD COLUMN BLOCK_ON_REFRESH_ERROR VARCHAR(1) NOT NULL DEFAULT 'N' CONSTRAINT ck_pipeline_block_refresh CHECK (BLOCK_ON_REFRESH_ERROR IN ('Y','N'));
ALTER TABLE AUD_CFG_PIPELINES_HISTORY ADD COLUMN BLOCK_ON_REFRESH_ERROR VARCHAR(1) DEFAULT 'N';
CREATE TABLE AUD_PIPELINE_REFRESHES (
    REFRESH_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROJECT_ID BIGINT NOT NULL REFERENCES CFG_PROJECTS(PROJECT_ID),
    PIPELINE_ID BIGINT NOT NULL REFERENCES CFG_PIPELINES(PIPELINE_ID),
    REFRESHED_AT TIMESTAMPTZ NOT NULL,
    ACTOR VARCHAR NOT NULL,
    ACTOR_KIND VARCHAR NOT NULL,
    STATUS VARCHAR NOT NULL CHECK (STATUS IN ('SUCCESS','FAILED')),
    METADATA_VERSION VARCHAR(64) NOT NULL,
    METADATA_SNAPSHOT TEXT,
    SNAPSHOT_REFRESH_ID BIGINT,
    BUNDLE_ID VARCHAR(64) REFERENCES AUD_PROJECT_BUNDLES(BUNDLE_ID),
    FINDINGS TEXT NOT NULL,
    UNIQUE (REFRESH_ID,PIPELINE_ID),
    FOREIGN KEY (SNAPSHOT_REFRESH_ID,PIPELINE_ID) REFERENCES AUD_PIPELINE_REFRESHES(REFRESH_ID,PIPELINE_ID),
    CHECK ((METADATA_SNAPSHOT IS NOT NULL AND SNAPSHOT_REFRESH_ID IS NULL) OR (METADATA_SNAPSHOT IS NULL AND SNAPSHOT_REFRESH_ID IS NOT NULL)),
    CHECK (STATUS <> 'SUCCESS' OR BUNDLE_ID IS NOT NULL)
);
CREATE INDEX ix_pipeline_refresh_latest ON AUD_PIPELINE_REFRESHES(PIPELINE_ID,REFRESH_ID DESC,PROJECT_ID);
CREATE INDEX ix_pipeline_refresh_good ON AUD_PIPELINE_REFRESHES(PIPELINE_ID,REFRESH_ID DESC) WHERE STATUS='SUCCESS';
CREATE INDEX ix_pipeline_refresh_reference ON AUD_PIPELINE_REFRESHES(SNAPSHOT_REFRESH_ID);
CREATE INDEX ix_pipeline_refresh_bundle ON AUD_PIPELINE_REFRESHES(BUNDLE_ID);
INSERT INTO AUD_PIPELINE_REFRESHES
(PROJECT_ID,PIPELINE_ID,REFRESHED_AT,ACTOR,ACTOR_KIND,STATUS,METADATA_VERSION,METADATA_SNAPSHOT,BUNDLE_ID,FINDINGS)
SELECT p.PROJECT_ID,r.PIPELINE_ID,COALESCE(r.END_DATE,r.START_DATE,CURRENT_TIMESTAMP),'etl-craft','SYSTEM','SUCCESS',r.METADATA_VERSION,r.METADATA_SNAPSHOT,r.BUNDLE_ID,'[]'
FROM AUD_PIPELINES_RUN_LOG r JOIN CFG_PIPELINES p ON p.PIPELINE_ID=r.PIPELINE_ID
WHERE r.STATUS='SUCCESS' AND r.METADATA_SNAPSHOT IS NOT NULL AND r.BUNDLE_ID IS NOT NULL
AND r.PIPELINE_RUN_ID=(SELECT MAX(older.PIPELINE_RUN_ID) FROM AUD_PIPELINES_RUN_LOG older WHERE older.PIPELINE_ID=r.PIPELINE_ID AND older.STATUS='SUCCESS' AND older.METADATA_SNAPSHOT IS NOT NULL AND older.BUNDLE_ID IS NOT NULL);
CREATE TRIGGER trg_actor_guard_aud_pipeline_refreshes BEFORE INSERT OR UPDATE OR DELETE ON AUD_PIPELINE_REFRESHES FOR EACH ROW EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_truncate_aud_pipeline_refreshes BEFORE TRUNCATE ON AUD_PIPELINE_REFRESHES FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_guard();
CREATE FUNCTION etl_craft_refresh_immutable() RETURNS trigger AS $$
BEGIN
 IF COALESCE(current_setting('etl_craft.purpose', true),'') <> 'retention' THEN
  RAISE EXCEPTION 'AUD_PIPELINE_REFRESHES is append-only; use etl-craft retention';
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_refresh_immutable BEFORE UPDATE OR DELETE ON AUD_PIPELINE_REFRESHES FOR EACH ROW EXECUTE FUNCTION etl_craft_refresh_immutable();
CREATE TRIGGER trg_truncate_refresh_immutable BEFORE TRUNCATE ON AUD_PIPELINE_REFRESHES FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_refresh_immutable();

