-- Durable stewardship file receipts, validation reasons and exact run admission.
CREATE TABLE AUD_UPLOADS (
 UPLOAD_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 PIPELINE_ID BIGINT REFERENCES CFG_PIPELINES(PIPELINE_ID),
 ACCOUNT VARCHAR(128) NOT NULL,
 FILE_NAME VARCHAR(255) NOT NULL,
 SHA256 VARCHAR(64),
 SIZE_BYTES BIGINT NOT NULL,
 PIPELINE_RUN_ID BIGINT REFERENCES AUD_PIPELINES_RUN_LOG(PIPELINE_RUN_ID),
 STATUS VARCHAR(16) NOT NULL CHECK (STATUS IN ('QUEUED','REFUSED','LOADED','FAILED')),
 REASON TEXT,
 UPLOADED_AT TIMESTAMPTZ NOT NULL,
 TAKEN_AT TIMESTAMPTZ,
 ENDED_AT TIMESTAMPTZ
);
CREATE INDEX ix_uploads_pipeline_queue ON AUD_UPLOADS(PIPELINE_ID,UPLOAD_ID) WHERE STATUS='QUEUED' AND PIPELINE_RUN_ID IS NULL;
CREATE INDEX ix_uploads_run ON AUD_UPLOADS(PIPELINE_RUN_ID,UPLOAD_ID);
CREATE INDEX ix_uploads_content ON AUD_UPLOADS(PIPELINE_ID,SHA256,STATUS);
CREATE INDEX ix_pipelines_stewardable ON CFG_PIPELINES(PROJECT_ID,PIPELINE_CODE) WHERE STEWARDABLE_FLAG='Y' AND ACTIVE_FLAG='Y';

CREATE TRIGGER trg_actor_guard_aud_uploads BEFORE INSERT OR UPDATE OR DELETE
ON AUD_UPLOADS FOR EACH ROW EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_truncate_aud_uploads BEFORE TRUNCATE ON AUD_UPLOADS FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_guard();
