-- etl-craft: check-account-token-identities
CREATE TABLE CFG_ACCOUNTS (
    ACCOUNT_ID BIGSERIAL PRIMARY KEY,
    ACCOUNT_NAME VARCHAR(128) NOT NULL UNIQUE CHECK (length(trim(ACCOUNT_NAME)) BETWEEN 1 AND 128),
    ACCOUNT_KIND VARCHAR(16) NOT NULL CHECK (ACCOUNT_KIND IN ('USER','SERVICE')),
    ROLE VARCHAR(16) NOT NULL CHECK (ROLE IN ('viewer','operator','developer','admin')),
    EMAIL VARCHAR(320),
    PASSWORD_HASH TEXT,
    OIDC_SUBJECT TEXT UNIQUE,
    ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    CREATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (ACCOUNT_KIND = 'USER' OR PASSWORD_HASH IS NULL)
);

CREATE FUNCTION etl_craft_accounts_no_delete() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
    RAISE EXCEPTION 'CFG_ACCOUNTS cannot be deleted; disable the account with ACTIVE_FLAG=N';
END;
$fn$;
CREATE TRIGGER trg_accounts_no_delete BEFORE DELETE OR TRUNCATE ON CFG_ACCOUNTS
FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_accounts_no_delete();

INSERT INTO CFG_ACCOUNTS (ACCOUNT_NAME, ACCOUNT_KIND, ROLE, CREATED_BY, UPDATED_BY)
SELECT NAME AS account_name, 'SERVICE' AS account_kind, ROLE AS role, current_setting('etl_craft.actor') AS created_by, current_setting('etl_craft.actor') AS updated_by FROM CFG_API_TOKENS ORDER BY TOKEN_ID;

ALTER TABLE CFG_API_TOKENS ADD COLUMN ACCOUNT_ID BIGINT REFERENCES CFG_ACCOUNTS(ACCOUNT_ID);
UPDATE CFG_API_TOKENS t SET ACCOUNT_ID=a.ACCOUNT_ID FROM CFG_ACCOUNTS a WHERE a.ACCOUNT_NAME=t.NAME;
ALTER TABLE CFG_API_TOKENS ALTER COLUMN ACCOUNT_ID SET NOT NULL;
ALTER TABLE CFG_API_TOKENS DROP COLUMN ROLE;
COMMENT ON TABLE CFG_API_TOKENS IS 'Opaque API credentials: SHA-256 hashes, account ownership and expiry; token values are never stored or cloned.';
