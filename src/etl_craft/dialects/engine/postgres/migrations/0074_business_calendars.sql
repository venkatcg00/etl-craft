-- A project's business calendars: weekend days and holidays its pipelines' schedules skip or move past.
CREATE TABLE CFG_CALENDARS (
    CALENDAR_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PROJECT_ID BIGINT NOT NULL REFERENCES CFG_PROJECTS(PROJECT_ID),
    CALENDAR_CODE VARCHAR NOT NULL,
    CALENDAR_NAME VARCHAR,
    WEEKEND_DAYS VARCHAR,
    ACTIVE_FLAG VARCHAR NOT NULL DEFAULT 'Y',
    CREATED_BY VARCHAR NOT NULL,
    CREATE_DATE TIMESTAMPTZ NOT NULL,
    UPDATED_BY VARCHAR NOT NULL,
    UPDATED_DATE TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_calendars_active CHECK (ACTIVE_FLAG IN ('Y','N')),
    CONSTRAINT ck_calendars_code CHECK (length(CALENDAR_CODE) > 0)
);
CREATE UNIQUE INDEX ux_calendars_code ON CFG_CALENDARS (PROJECT_ID, CALENDAR_CODE);
-- One holiday of a business calendar.
CREATE TABLE CFG_CALENDAR_HOLIDAYS (
    HOLIDAY_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CALENDAR_ID BIGINT NOT NULL REFERENCES CFG_CALENDARS(CALENDAR_ID),
    HOLIDAY_DATE DATE NOT NULL,
    HOLIDAY_NAME VARCHAR,
    ACTIVE_FLAG VARCHAR NOT NULL DEFAULT 'Y',
    CREATED_BY VARCHAR NOT NULL,
    CREATE_DATE TIMESTAMPTZ NOT NULL,
    UPDATED_BY VARCHAR NOT NULL,
    UPDATED_DATE TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_holidays_active CHECK (ACTIVE_FLAG IN ('Y','N'))
);
CREATE UNIQUE INDEX ux_holidays_date ON CFG_CALENDAR_HOLIDAYS (CALENDAR_ID, HOLIDAY_DATE);
-- Immutable versions of CFG_CALENDARS rows.
CREATE TABLE AUD_CFG_CALENDARS_HISTORY (
    CHANGE_ID BIGINT PRIMARY KEY,
    VALID_FROM TIMESTAMPTZ NOT NULL,
    VALID_TO TIMESTAMPTZ NOT NULL,
    CURRENT_FLAG VARCHAR(1) NOT NULL,
    OPERATION VARCHAR NOT NULL,
    ACTOR VARCHAR NOT NULL,
    ACTOR_KIND VARCHAR NOT NULL,
    MIGRATION VARCHAR,
    CALENDAR_ID bigint,
    PROJECT_ID bigint,
    CALENDAR_CODE character varying,
    CALENDAR_NAME character varying,
    WEEKEND_DAYS character varying,
    ACTIVE_FLAG character varying,
    CREATED_BY character varying,
    CREATE_DATE timestamp with time zone,
    UPDATED_BY character varying,
    UPDATED_DATE timestamp with time zone,
    UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Immutable versions of CFG_CALENDAR_HOLIDAYS rows.
CREATE TABLE AUD_CFG_CALENDAR_HOLIDAYS_HISTORY (
    CHANGE_ID BIGINT PRIMARY KEY,
    VALID_FROM TIMESTAMPTZ NOT NULL,
    VALID_TO TIMESTAMPTZ NOT NULL,
    CURRENT_FLAG VARCHAR(1) NOT NULL,
    OPERATION VARCHAR NOT NULL,
    ACTOR VARCHAR NOT NULL,
    ACTOR_KIND VARCHAR NOT NULL,
    MIGRATION VARCHAR,
    HOLIDAY_ID bigint,
    CALENDAR_ID bigint,
    HOLIDAY_DATE date,
    HOLIDAY_NAME character varying,
    ACTIVE_FLAG character varying,
    CREATED_BY character varying,
    CREATE_DATE timestamp with time zone,
    UPDATED_BY character varying,
    UPDATED_DATE timestamp with time zone,
    UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE CFG_PIPELINES ADD COLUMN CALENDAR_ID BIGINT REFERENCES CFG_CALENDARS(CALENDAR_ID);
ALTER TABLE CFG_PIPELINES ADD COLUMN NON_BUSINESS_DAY VARCHAR(17) NOT NULL DEFAULT 'SKIP'
    CHECK (NON_BUSINESS_DAY IN ('SKIP','NEXT_BUSINESS_DAY'));
CREATE INDEX ix_pipelines_calendar ON CFG_PIPELINES (CALENDAR_ID) WHERE CALENDAR_ID IS NOT NULL;
CREATE INDEX ix_sql_edits_calendars ON AUD_CFG_CALENDARS_HISTORY(PROJECT_ID) WHERE substr(ACTOR,1,4)='sql:';
CREATE INDEX ix_sql_edits_calendar_holidays ON AUD_CFG_CALENDAR_HOLIDAYS_HISTORY(CALENDAR_ID) WHERE substr(ACTOR,1,4)='sql:';

CREATE OR REPLACE FUNCTION etl_craft_config_project(table_name text, row_data jsonb)
RETURNS bigint LANGUAGE plpgsql AS $$
BEGIN
    CASE
        WHEN upper(table_name) IN ('CFG_PIPELINES','CFG_TABLES','CFG_CALENDARS') THEN
            RETURN (row_data->>'project_id')::bigint;
        WHEN upper(table_name) IN ('CFG_TASKS','CFG_PIPELINE_DEPENDENCY','CFG_TASK_DEPENDENCY','CFG_BUSINESS_RULES') THEN
            RETURN (SELECT p.PROJECT_ID FROM CFG_PIPELINES p WHERE p.PIPELINE_ID=(row_data->>'pipeline_id')::bigint);
        WHEN upper(table_name)='CFG_TASK_PARAMETERS' THEN
            RETURN (SELECT p.PROJECT_ID FROM CFG_TASKS t JOIN CFG_PIPELINES p ON p.PIPELINE_ID=t.PIPELINE_ID WHERE t.TASK_ID=(row_data->>'task_id')::bigint);
        WHEN upper(table_name)='CFG_COLUMNS' THEN
            RETURN (SELECT t.PROJECT_ID FROM CFG_TABLES t WHERE t.TABLE_ID=(row_data->>'table_id')::bigint);
        WHEN upper(table_name)='CFG_CALENDAR_HOLIDAYS' THEN
            RETURN (SELECT c.PROJECT_ID FROM CFG_CALENDARS c WHERE c.CALENDAR_ID=(row_data->>'calendar_id')::bigint);
        ELSE RETURN NULL;
    END CASE;
END; $$;

CREATE OR REPLACE FUNCTION etl_craft_pipeline_calendar_project() RETURNS trigger AS $$
BEGIN
    IF NEW.CALENDAR_ID IS NOT NULL AND (SELECT c.PROJECT_ID FROM CFG_CALENDARS c WHERE c.CALENDAR_ID=NEW.CALENDAR_ID) IS DISTINCT FROM NEW.PROJECT_ID THEN
        RAISE EXCEPTION 'CFG_PIPELINES: CALENDAR_ID must name a calendar of the pipeline''s own project';
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;
-- A pipeline's calendar belongs to the pipeline's own project.
CREATE TRIGGER trg_pipelines_calendar_project BEFORE INSERT OR UPDATE OF CALENDAR_ID, PROJECT_ID ON CFG_PIPELINES
    FOR EACH ROW EXECUTE FUNCTION etl_craft_pipeline_calendar_project();
