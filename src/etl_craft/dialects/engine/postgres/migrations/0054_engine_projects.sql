CREATE TABLE CFG_PROJECTS (
    PROJECT_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PROJECT_CODE VARCHAR NOT NULL,
    PROJECT_NAME VARCHAR NOT NULL,
    TIMEZONE VARCHAR NOT NULL DEFAULT 'UTC',
    DEFAULT_POOL VARCHAR(128) NOT NULL REFERENCES CFG_POOLS(POOL_NAME),
    MAX_RUNNING_TASKS INTEGER NOT NULL DEFAULT 8 CHECK (MAX_RUNNING_TASKS > 0),
    ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    CREATED_BY VARCHAR NOT NULL,
    CREATE_DATE TIMESTAMPTZ NOT NULL,
    UPDATED_BY VARCHAR NOT NULL,
    UPDATED_DATE TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_projects_code CHECK (PROJECT_CODE ~ '^[A-Za-z][A-Za-z0-9_]{0,127}$')
);
