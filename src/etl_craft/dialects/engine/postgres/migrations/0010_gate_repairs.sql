-- Keep a reopened run's output revision unchanged until its repair succeeds.
ALTER TABLE AUD_PIPELINES_RUN_LOG ADD COLUMN REPAIR_PENDING VARCHAR NOT NULL DEFAULT 'N'
CONSTRAINT ck_run_repair_pending CHECK (REPAIR_PENDING IN ('Y','N'));
UPDATE AUD_PIPELINES_RUN_LOG SET REPAIR_PENDING = 'Y'
WHERE STATUS = 'IN-PROGRESS' AND EXISTS (
SELECT 1 FROM AUD_RUN_INTERVENTIONS i
WHERE i.PIPELINE_RUN_ID = AUD_PIPELINES_RUN_LOG.PIPELINE_RUN_ID AND i.ACTION = 'REOPEN');
