$fn$;
CREATE TRIGGER trg_cfg_group_members_no_delete BEFORE DELETE OR TRUNCATE ON CFG_GROUP_MEMBERS
FOR EACH STATEMENT EXECUTE FUNCTION cfg_group_members_no_delete();
