-- Administrator-managed permission group identities; inactive names stay reserved.
CREATE TABLE CFG_GROUPS (
    GROUP_ID BIGSERIAL PRIMARY KEY,
    GROUP_NAME VARCHAR(128) NOT NULL UNIQUE CHECK (length(trim(GROUP_NAME)) BETWEEN 1 AND 128),
    DESCRIPTION TEXT,
    ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    CREATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Explicit account memberships; ACTIVE_FLAG retires a membership without deleting it.
CREATE TABLE CFG_GROUP_MEMBERS (
    GROUP_MEMBER_ID BIGSERIAL PRIMARY KEY,
    GROUP_ID BIGINT NOT NULL REFERENCES CFG_GROUPS(GROUP_ID),
    ACCOUNT_ID BIGINT NOT NULL REFERENCES CFG_ACCOUNTS(ACCOUNT_ID),
    ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    CREATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_group_member_identity UNIQUE (GROUP_ID, ACCOUNT_ID)
);
-- Group viewer/operator grants on exactly one pipeline code or tag.
CREATE TABLE CFG_PIPELINE_GRANTS (
    PIPELINE_GRANT_ID BIGSERIAL PRIMARY KEY,
    GROUP_ID BIGINT NOT NULL REFERENCES CFG_GROUPS(GROUP_ID),
    PIPELINE_CODE VARCHAR REFERENCES CFG_PIPELINES(PIPELINE_CODE),
    TAG VARCHAR,
    ROLE VARCHAR(16) NOT NULL CHECK (ROLE IN ('viewer','operator')),
    ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    CREATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((PIPELINE_CODE IS NULL) <> (TAG IS NULL))
);
CREATE UNIQUE INDEX ux_pipeline_grant_code ON CFG_PIPELINE_GRANTS (GROUP_ID, PIPELINE_CODE) WHERE PIPELINE_CODE IS NOT NULL;
CREATE UNIQUE INDEX ux_pipeline_grant_tag ON CFG_PIPELINE_GRANTS (GROUP_ID, TAG) WHERE TAG IS NOT NULL;
CREATE FUNCTION cfg_groups_no_delete() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN RAISE EXCEPTION 'CFG_GROUPS: use ACTIVE_FLAG=N instead of deleting'; END;
$fn$;
CREATE TRIGGER trg_cfg_groups_no_delete BEFORE DELETE OR TRUNCATE ON CFG_GROUPS
FOR EACH STATEMENT EXECUTE FUNCTION cfg_groups_no_delete();
