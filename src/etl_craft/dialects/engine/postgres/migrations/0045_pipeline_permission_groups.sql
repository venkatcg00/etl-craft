BEGIN RAISE EXCEPTION 'CFG_PIPELINE_GRANTS: use ACTIVE_FLAG=N instead of deleting'; END;
$fn$;
CREATE TRIGGER trg_cfg_pipeline_grants_no_delete BEFORE DELETE OR TRUNCATE ON CFG_PIPELINE_GRANTS
FOR EACH STATEMENT EXECUTE FUNCTION cfg_pipeline_grants_no_delete();
