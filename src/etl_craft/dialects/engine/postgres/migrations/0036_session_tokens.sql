-- Service tokens, user access tokens and the refresh tokens that renew access; existing user
-- sessions become access tokens.
ALTER TABLE CFG_API_TOKENS ADD COLUMN TOKEN_KIND VARCHAR(8) NOT NULL DEFAULT 'SERVICE' CONSTRAINT ck_api_token_kind CHECK (TOKEN_KIND IN ('SERVICE','ACCESS','REFRESH'));
ALTER TABLE CFG_API_TOKENS ADD COLUMN REFRESH_TOKEN_ID BIGINT REFERENCES CFG_API_TOKENS(TOKEN_ID);
UPDATE CFG_API_TOKENS t SET TOKEN_KIND='ACCESS' FROM CFG_ACCOUNTS a WHERE a.ACCOUNT_ID=t.ACCOUNT_ID AND a.ACCOUNT_KIND='USER';
ALTER TABLE CFG_API_TOKENS ADD CONSTRAINT ck_api_token_refresh CHECK (REFRESH_TOKEN_ID IS NULL OR TOKEN_KIND='ACCESS');
