CREATE TABLE AUD_ANNOUNCEMENTS (
    ANNOUNCEMENT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LEVEL VARCHAR(8) NOT NULL CHECK (LEVEL IN ('INFO','WARNING','CRITICAL')),
    MESSAGE VARCHAR(500) NOT NULL,
    STARTS_AT TIMESTAMPTZ NOT NULL,
    ENDS_AT TIMESTAMPTZ,
    REASON VARCHAR NOT NULL,
    CREATED_BY VARCHAR NOT NULL,
    CREATED_BY_KIND VARCHAR NOT NULL,
    CREATED_AT TIMESTAMPTZ NOT NULL,
    ENDED_BY VARCHAR,
    ENDED_BY_KIND VARCHAR,
    ENDED_AT TIMESTAMPTZ,
    UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (ENDS_AT IS NULL OR ENDS_AT > STARTS_AT)
);
CREATE INDEX ix_announcements_current ON AUD_ANNOUNCEMENTS (STARTS_AT) WHERE ENDED_AT IS NULL;
CREATE TRIGGER trg_actor_guard_aud_announcements BEFORE INSERT OR UPDATE OR DELETE ON AUD_ANNOUNCEMENTS FOR EACH ROW EXECUTE FUNCTION etl_craft_guard();
CREATE TRIGGER trg_truncate_aud_announcements BEFORE TRUNCATE ON AUD_ANNOUNCEMENTS FOR EACH STATEMENT EXECUTE FUNCTION etl_craft_guard();
