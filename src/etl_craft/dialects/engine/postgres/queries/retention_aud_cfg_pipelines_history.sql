-- Keep the bounded candidate array as an initplan for indexed target lookups.
DELETE FROM AUD_CFG_PIPELINES_HISTORY WHERE CHANGE_ID = ANY(ARRAY(
SELECT
  t.CHANGE_ID AS row_id
FROM AUD_CFG_PIPELINES_HISTORY AS t
WHERE
  (
    t.PROJECT_ID = :project_id
  ) AND t.CURRENT_FLAG = 'N' AND t.VALID_TO < :cutoff
  AND (
    SELECT r.CHANGE_ID AS reserved FROM AUD_CFG_PIPELINES_HISTORY r
    WHERE r.PIPELINE_ID=t.PIPELINE_ID AND r.PROJECT_ID=t.PROJECT_ID AND r.MIGRATION='rename'
      AND (r.CHANGE_ID=t.CHANGE_ID OR r.CHANGE_ID=(
        SELECT MIN(n.CHANGE_ID) AS next_change FROM AUD_CFG_PIPELINES_HISTORY n
        WHERE n.PIPELINE_ID=t.PIPELINE_ID AND n.CHANGE_ID>t.CHANGE_ID
      ))
    LIMIT 1 OFFSET 0
  ) IS NULL
ORDER BY
  t.CHANGE_ID
LIMIT 10000
))
