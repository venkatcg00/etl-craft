SELECT p.PIPELINE_CODE AS pipeline_code,r.STATUS AS status,r.FINDINGS AS findings,
p.BLOCK_ON_REFRESH_ERROR AS block_on_refresh_error,
EXISTS(SELECT 1 AS found FROM AUD_PIPELINE_REFRESHES good WHERE good.PIPELINE_ID=p.PIPELINE_ID AND good.STATUS='SUCCESS') AS has_baseline
FROM CFG_PIPELINES p
LEFT JOIN LATERAL (
SELECT latest.STATUS AS status,latest.FINDINGS AS findings,latest.REFRESH_ID AS refresh_id
FROM AUD_PIPELINE_REFRESHES latest WHERE latest.PIPELINE_ID=p.PIPELINE_ID
ORDER BY latest.REFRESH_ID DESC LIMIT 1
) r ON TRUE
WHERE p.PROJECT_ID=:project_id AND p.ACTIVE_FLAG='Y' AND (r.status='FAILED' OR r.refresh_id IS NULL)
ORDER BY p.PIPELINE_CODE
