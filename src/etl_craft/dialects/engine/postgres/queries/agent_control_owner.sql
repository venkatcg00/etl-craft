SELECT t.PIPELINE_RUN_ID AS pipeline_run_id, a.STATUS AS status
FROM AUD_TASK_ATTEMPTS a JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID=a.TASK_RUN_ID
WHERE a.STATUS IN ('CLAIMED','RUNNING','LOST','SUCCESS','FAILED','TIMED_OUT','CANCELLED','HANDED_OFF')
AND a.ATTEMPT_ID=:attempt_id AND a.OWNER_ID=:owner AND EXISTS (SELECT 1 FROM AUD_CONTROL_REQUESTS c WHERE c.STATUS <> 'COMPLETED' AND a.ATTEMPT_ID IN (SELECT value::bigint FROM jsonb_array_elements_text(c.ATTEMPT_IDS::jsonb)))
