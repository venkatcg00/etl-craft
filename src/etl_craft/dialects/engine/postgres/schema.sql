CREATE FUNCTION etl_craft_lineage_history_guard() RETURNS trigger AS $$
BEGIN
    IF COALESCE(current_setting('etl_craft.actor', true), '') = '' THEN
        RAISE EXCEPTION USING MESSAGE = upper(TG_TABLE_NAME) || ' is written only by etl-craft; record lineage with etl-craft lineage';
    END IF;
    IF TG_TABLE_NAME = 'aud_lineage_versions' AND TG_OP = 'UPDATE' THEN
        IF OLD.current_flag='Y' AND NEW.current_flag='N' AND NEW.valid_to >= OLD.valid_from
           AND to_jsonb(NEW) - ARRAY['valid_to','current_flag'] = to_jsonb(OLD) - ARRAY['valid_to','current_flag'] THEN
            RETURN NEW;
        END IF;
    END IF;
    RAISE EXCEPTION USING MESSAGE = upper(TG_TABLE_NAME) || ' rejects ' || TG_OP || ': lineage history is append-only; only closing a current version is allowed; recompute with etl-craft lineage';
END;
$$ LANGUAGE plpgsql;
