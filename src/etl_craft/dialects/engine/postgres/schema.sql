);
CREATE INDEX ix_tasks_target ON CFG_TASKS (TARGET_TABLE_ID) WHERE TARGET_TABLE_ID IS NOT NULL;
CREATE UNIQUE INDEX ux_tasks_code_identity
    ON CFG_TASKS (PIPELINE_ID, TASK_CODE);
