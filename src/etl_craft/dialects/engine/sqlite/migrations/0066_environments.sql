    REQUESTED_AT TIMESTAMP NOT NULL,
    ACKNOWLEDGED_AT TIMESTAMP,
    COMPLETED_AT TIMESTAMP,
    MESSAGE TEXT NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT '1970-01-01 00:00:00.000000+00:00'
);
