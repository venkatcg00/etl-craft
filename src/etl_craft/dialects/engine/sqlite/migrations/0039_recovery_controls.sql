-- etl-craft: rebuild-metadata
-- Preserve request identities and autoincrement history while extending action values.
CREATE TEMP TABLE etl_craft_control_sequence AS SELECT name, seq FROM sqlite_sequence WHERE name='AUD_CONTROL_REQUESTS';
CREATE TABLE AUD_CONTROL_REQUESTS_new (
    CONTROL_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    REQUEST_KEY VARCHAR(128) NOT NULL UNIQUE,
    PIPELINE_RUN_ID BIGINT NOT NULL REFERENCES AUD_PIPELINES_RUN_LOG(PIPELINE_RUN_ID),
    TASK_ID BIGINT REFERENCES CFG_TASKS(TASK_ID),
    ACTION VARCHAR(16) NOT NULL CONSTRAINT ck_control_action CHECK (ACTION IN ('HOLD','RELEASE','STOP','ABORT','RECOVER','RESTART','RUN_PAUSED')),
    STATUS VARCHAR(16) NOT NULL CHECK (STATUS IN ('REQUESTED','ACKNOWLEDGED','COMPLETED')),
    ATTEMPT_IDS TEXT NOT NULL,
    REQUESTED_BY VARCHAR(128) NOT NULL,
    REQUESTED_BY_KIND VARCHAR(8) NOT NULL CHECK (REQUESTED_BY_KIND IN ('USER','SERVICE','SYSTEM')),
    REASON TEXT NOT NULL CHECK (length(trim(REASON)) > 0),
    REQUESTED_AT TIMESTAMP NOT NULL,
    ACKNOWLEDGED_AT TIMESTAMP,
    COMPLETED_AT TIMESTAMP,
    MESSAGE TEXT NOT NULL
);
INSERT INTO AUD_CONTROL_REQUESTS_new SELECT * FROM AUD_CONTROL_REQUESTS;
DROP TABLE AUD_CONTROL_REQUESTS;
ALTER TABLE AUD_CONTROL_REQUESTS_new RENAME TO AUD_CONTROL_REQUESTS;
UPDATE sqlite_sequence SET seq=max(seq, coalesce((SELECT seq FROM etl_craft_control_sequence), seq)) WHERE name='AUD_CONTROL_REQUESTS';
INSERT INTO sqlite_sequence (name, seq) SELECT name, seq FROM etl_craft_control_sequence s WHERE NOT EXISTS (SELECT 1 FROM sqlite_sequence c WHERE c.name=s.name);
DROP TABLE etl_craft_control_sequence;
CREATE INDEX ix_control_scope ON AUD_CONTROL_REQUESTS (PIPELINE_RUN_ID, TASK_ID, CONTROL_ID);
CREATE INDEX ix_control_pending ON AUD_CONTROL_REQUESTS (PIPELINE_RUN_ID) WHERE STATUS <> 'COMPLETED';
CREATE TRIGGER trg_control_identity_update BEFORE UPDATE ON AUD_CONTROL_REQUESTS
WHEN OLD.STATUS='COMPLETED' OR NEW.CONTROL_ID IS NOT OLD.CONTROL_ID
OR NEW.REQUEST_KEY IS NOT OLD.REQUEST_KEY
OR NEW.PIPELINE_RUN_ID IS NOT OLD.PIPELINE_RUN_ID
OR NEW.TASK_ID IS NOT OLD.TASK_ID
OR NEW.ACTION IS NOT OLD.ACTION
OR NEW.ATTEMPT_IDS IS NOT OLD.ATTEMPT_IDS
OR NEW.REQUESTED_BY IS NOT OLD.REQUESTED_BY
OR NEW.REQUESTED_BY_KIND IS NOT OLD.REQUESTED_BY_KIND
OR NEW.REASON IS NOT OLD.REASON
OR NEW.REQUESTED_AT IS NOT OLD.REQUESTED_AT
BEGIN SELECT RAISE(ABORT, 'control request identity and completed outcome are immutable; submit a new control'); END;
CREATE TRIGGER trg_control_identity_delete BEFORE DELETE ON AUD_CONTROL_REQUESTS
WHEN etl_craft_purpose() <> 'retention'
BEGIN SELECT RAISE(ABORT, 'control request is immutable; use etl-craft retention'); END;
