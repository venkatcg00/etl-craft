-- Live process connection reservations, retained after clean or expired ownership ends.
CREATE TABLE AUD_CONNECTION_RESERVATIONS (
    RESERVATION_ID VARCHAR(64) PRIMARY KEY,
    ROLE VARCHAR(16) NOT NULL CHECK (ROLE IN ('CONTROLLER','UI','RUN')),
    HOST VARCHAR NOT NULL,
    PID BIGINT NOT NULL,
    BIRTH_TIME DOUBLE PRECISION NOT NULL,
    POOL_CONNECTIONS INTEGER NOT NULL CHECK (POOL_CONNECTIONS > 0),
    SESSION_CONNECTIONS INTEGER NOT NULL CHECK (SESSION_CONNECTIONS >= 0),
    LOCAL_TASK_CONNECTIONS INTEGER NOT NULL CHECK (LOCAL_TASK_CONNECTIONS >= 0),
    BACKEND_PID INTEGER NOT NULL,
    BACKEND_STARTED_AT TIMESTAMP NOT NULL,
    STARTED_AT TIMESTAMP NOT NULL,
    HEARTBEAT_AT TIMESTAMP NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    STOPPED_AT TIMESTAMP,
    ACTOR VARCHAR NOT NULL,
    ACTOR_KIND VARCHAR NOT NULL
);
CREATE INDEX ix_connection_reservations_active ON AUD_CONNECTION_RESERVATIONS (EXPIRES_AT) WHERE STOPPED_AT IS NULL;
CREATE TRIGGER trg_actor_guard_aud_connection_reservations_insert BEFORE INSERT ON AUD_CONNECTION_RESERVATIONS
BEGIN SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_CONNECTION_RESERVATIONS is written only by etl-craft') END; END;
CREATE TRIGGER trg_actor_guard_aud_connection_reservations_update BEFORE UPDATE ON AUD_CONNECTION_RESERVATIONS
BEGIN SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_CONNECTION_RESERVATIONS is written only by etl-craft') END; END;
CREATE TRIGGER trg_actor_guard_aud_connection_reservations_delete BEFORE DELETE ON AUD_CONNECTION_RESERVATIONS
BEGIN SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_CONNECTION_RESERVATIONS is written only by etl-craft') END; SELECT RAISE(ABORT, 'AUD_CONNECTION_RESERVATIONS retains process history'); END;
