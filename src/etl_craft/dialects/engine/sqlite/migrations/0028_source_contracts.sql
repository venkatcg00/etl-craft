    OPERATION VARCHAR NOT NULL,
    ACTOR VARCHAR NOT NULL,
    ACTOR_KIND VARCHAR NOT NULL,
    MIGRATION VARCHAR,
    TABLE_ID BIGINT,
    CATALOG_NAME VARCHAR,
    SCHEMA_NAME VARCHAR,
    TABLE_NAME VARCHAR,
    OBJECT_KIND VARCHAR,
    ACTIVE_FLAG VARCHAR,
    CREATED_BY VARCHAR,
    CREATE_DATE TIMESTAMP,
    UPDATED_BY VARCHAR,
    UPDATED_DATE TIMESTAMP
);

