BEGIN
 SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_PIPELINE_REFRESHES is written only by etl-craft') END;
 SELECT CASE WHEN etl_craft_purpose() <> 'retention' THEN RAISE(ABORT, 'AUD_PIPELINE_REFRESHES is append-only; use etl-craft retention') END;
END;
CREATE TRIGGER trg_actor_guard_aud_pipeline_refreshes_delete BEFORE DELETE ON AUD_PIPELINE_REFRESHES
BEGIN
