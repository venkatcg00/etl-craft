-- Persist the exact task selection and keep conflicting executions in one admission slot.
ALTER TABLE AUD_PIPELINES_RUN_LOG ADD COLUMN TASK_SELECTION TEXT;
ALTER TABLE AUD_PIPELINES_RUN_LOG ADD COLUMN EXCLUSIVE_RUN VARCHAR(1) NOT NULL DEFAULT 'Y' CONSTRAINT ck_run_exclusive CHECK (EXCLUSIVE_RUN IN ('Y','N') AND (EXCLUSIVE_RUN='Y' OR TASK_SELECTION IS NOT NULL));
DROP INDEX ux_pipeline_run_one_active;
CREATE UNIQUE INDEX ux_pipeline_run_one_active ON AUD_PIPELINES_RUN_LOG (PIPELINE_ID) WHERE STATUS='IN-PROGRESS' AND EXCLUSIVE_RUN='Y';
