INSERT INTO CFG_TASK_PARAMETERS (TASK_ID,PARAMETER_NAME,PARAMETER_VALUE)
SELECT t.TASK_ID AS task_id,'SCRIPT_KIND' AS parameter_name,'INGESTION' AS parameter_value
FROM CFG_TASKS t WHERE t.HANDLER='PYTHON'
AND NOT EXISTS (SELECT 1 FROM CFG_TASK_PARAMETERS p
                WHERE p.TASK_ID=t.TASK_ID AND p.PARAMETER_NAME='SCRIPT_KIND');
UPDATE CFG_TASK_PARAMETERS SET PARAMETER_VALUE='INGESTION',ACTIVE_FLAG='Y'
WHERE PARAMETER_NAME='SCRIPT_KIND' AND TASK_ID IN
(SELECT TASK_ID AS task_id FROM CFG_TASKS WHERE HANDLER='PYTHON');
