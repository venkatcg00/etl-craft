-- Durable ownership of resources shared by task attempts and standalone actions.
CREATE TABLE AUD_RESOURCE_LOCKS (
    LOCK_KEY BIGINT PRIMARY KEY,
    RESOURCE_NAME VARCHAR NOT NULL,
    HOLDER_ID VARCHAR NOT NULL,
    ATTEMPT_ID BIGINT REFERENCES AUD_TASK_ATTEMPTS(ATTEMPT_ID),
    OWNER_ID VARCHAR NOT NULL,
    ACTOR VARCHAR NOT NULL,
    ACTOR_KIND VARCHAR NOT NULL,
    ACQUIRED_AT TIMESTAMP NOT NULL,
    LEASE_EXPIRES_AT TIMESTAMP NOT NULL
);
CREATE INDEX ix_resource_locks_attempt ON AUD_RESOURCE_LOCKS (ATTEMPT_ID)
    WHERE ATTEMPT_ID IS NOT NULL;

