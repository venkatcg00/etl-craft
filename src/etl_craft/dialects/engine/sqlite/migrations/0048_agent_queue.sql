-- Registry identities are derived from agent tokens, never supplied by a request.
CREATE TABLE AUD_AGENTS (
    AGENT_ID BIGINT PRIMARY KEY REFERENCES CFG_API_TOKENS(TOKEN_ID),
    POOL VARCHAR NOT NULL,
    HOST VARCHAR NOT NULL,
    VERSION VARCHAR NOT NULL,
    PYTHON_SLOTS INTEGER NOT NULL CHECK (PYTHON_SLOTS >= 0),
    WAREHOUSE_SLOTS INTEGER NOT NULL CHECK (WAREHOUSE_SLOTS >= 0),
    STARTED_AT TIMESTAMP NOT NULL,
    HEARTBEAT_AT TIMESTAMP NOT NULL,
    STATUS VARCHAR NOT NULL CHECK (STATUS IN ('ACTIVE','DRAINING','GONE')),
    RESOURCE_REPORT TEXT NOT NULL
);
CREATE TABLE AUD_AGENT_COMMANDS (
    COMMAND_ID INTEGER PRIMARY KEY,
    AGENT_ID BIGINT NOT NULL REFERENCES AUD_AGENTS(AGENT_ID),
    COMMAND VARCHAR NOT NULL CHECK (COMMAND IN ('DRAIN','RESUME','STOP')),
    ACTOR VARCHAR NOT NULL,
    ACTOR_KIND VARCHAR NOT NULL,
    REQUESTED_AT TIMESTAMP NOT NULL,
    ACKNOWLEDGED_AT TIMESTAMP
);
CREATE INDEX ix_agent_commands_pending ON AUD_AGENT_COMMANDS (AGENT_ID, COMMAND_ID)
    WHERE ACKNOWLEDGED_AT IS NULL;
ALTER TABLE AUD_TASK_ATTEMPTS ADD COLUMN POOL VARCHAR NOT NULL DEFAULT 'default';
ALTER TABLE AUD_TASK_ATTEMPTS ADD COLUMN SLOT_KIND VARCHAR NOT NULL DEFAULT 'warehouse' CHECK (SLOT_KIND IN ('python','warehouse'));
ALTER TABLE AUD_TASK_ATTEMPTS ADD COLUMN PRIORITY INTEGER NOT NULL DEFAULT 0;
ALTER TABLE AUD_TASK_ATTEMPTS ADD COLUMN CANCEL_REQUESTED_AT TIMESTAMP;
ALTER TABLE AUD_TASK_ATTEMPTS ADD COLUMN CANCEL_ACKNOWLEDGED_AT TIMESTAMP;
CREATE INDEX ix_attempt_queue ON AUD_TASK_ATTEMPTS (POOL, SLOT_KIND, PRIORITY DESC, QUEUED_AT)
    WHERE STATUS = 'QUEUED';

-- Admission flags remain typed across queue delivery and controller restarts.
ALTER TABLE AUD_TASK_ATTEMPTS ADD COLUMN FORCE_FLAG VARCHAR(1) NOT NULL DEFAULT 'N' CHECK (FORCE_FLAG IN ('Y','N'));
ALTER TABLE AUD_TASK_ATTEMPTS ADD COLUMN RERUN_FLAG VARCHAR(1) NOT NULL DEFAULT 'N' CHECK (RERUN_FLAG IN ('Y','N'));
-- Shared live logs are readable from every API copy before external log storage is configured.
CREATE TABLE AUD_ATTEMPT_LOG_CHUNKS (
    ATTEMPT_ID BIGINT NOT NULL REFERENCES AUD_TASK_ATTEMPTS(ATTEMPT_ID),
    SEQUENCE_NUMBER INTEGER NOT NULL CHECK (SEQUENCE_NUMBER >= 0),
    CONTENT_SHA256 VARCHAR(64) NOT NULL,
    CONTENT TEXT NOT NULL CHECK (length(CAST(CONTENT AS BLOB)) <= 65536),
    BYTE_OFFSET BIGINT NOT NULL CHECK (BYTE_OFFSET >= 0),
    BYTE_LENGTH INTEGER NOT NULL CHECK (BYTE_LENGTH BETWEEN 0 AND 65536),
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT pk_attempt_log_chunk PRIMARY KEY (ATTEMPT_ID, SEQUENCE_NUMBER)
);
CREATE INDEX ix_agent_ending_receipt ON AUD_ACTIONS ((json_extract(ARGUMENTS, '$.attempt_id')))
    WHERE COMMAND='agent report' AND json_extract(ARGUMENTS, '$.operation')='END';
