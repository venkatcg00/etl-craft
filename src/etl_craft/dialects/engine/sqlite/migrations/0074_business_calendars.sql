-- A project's business calendars: weekend days and holidays its pipelines' schedules skip or move past.
CREATE TABLE CFG_CALENDARS (
    CALENDAR_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    PROJECT_ID BIGINT NOT NULL REFERENCES CFG_PROJECTS(PROJECT_ID),
    CALENDAR_CODE VARCHAR NOT NULL,
    CALENDAR_NAME VARCHAR,
    WEEKEND_DAYS VARCHAR,
    ACTIVE_FLAG VARCHAR NOT NULL DEFAULT 'Y',
    CREATED_BY VARCHAR NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    UPDATED_BY VARCHAR NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    CONSTRAINT ck_calendars_active CHECK (ACTIVE_FLAG IN ('Y','N')),
    CONSTRAINT ck_calendars_code CHECK (length(CALENDAR_CODE) > 0)
);
CREATE UNIQUE INDEX ux_calendars_code ON CFG_CALENDARS (PROJECT_ID, CALENDAR_CODE);
-- One holiday of a business calendar.
CREATE TABLE CFG_CALENDAR_HOLIDAYS (
    HOLIDAY_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    CALENDAR_ID BIGINT NOT NULL REFERENCES CFG_CALENDARS(CALENDAR_ID),
    HOLIDAY_DATE DATE NOT NULL,
    HOLIDAY_NAME VARCHAR,
    ACTIVE_FLAG VARCHAR NOT NULL DEFAULT 'Y',
    CREATED_BY VARCHAR NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    UPDATED_BY VARCHAR NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    CONSTRAINT ck_holidays_active CHECK (ACTIVE_FLAG IN ('Y','N')),
    CONSTRAINT ck_holidays_date CHECK (HOLIDAY_DATE = date(HOLIDAY_DATE))
);
CREATE UNIQUE INDEX ux_holidays_date ON CFG_CALENDAR_HOLIDAYS (CALENDAR_ID, HOLIDAY_DATE);
-- Immutable versions of CFG_CALENDARS rows.
CREATE TABLE AUD_CFG_CALENDARS_HISTORY (
    CHANGE_ID BIGINT PRIMARY KEY,
    VALID_FROM TIMESTAMP NOT NULL,
    VALID_TO TIMESTAMP NOT NULL,
    CURRENT_FLAG VARCHAR(1) NOT NULL,
    OPERATION VARCHAR NOT NULL,
    ACTOR VARCHAR NOT NULL,
    ACTOR_KIND VARCHAR NOT NULL,
    MIGRATION VARCHAR,
    CALENDAR_ID BIGINT,
    PROJECT_ID BIGINT,
    CALENDAR_CODE VARCHAR,
    CALENDAR_NAME VARCHAR,
    WEEKEND_DAYS VARCHAR,
    ACTIVE_FLAG VARCHAR,
    CREATED_BY VARCHAR,
    CREATE_DATE TIMESTAMP,
    UPDATED_BY VARCHAR,
    UPDATED_DATE TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT '1970-01-01 00:00:00.000000+00:00'
