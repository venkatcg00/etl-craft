    ACTOR VARCHAR NOT NULL,
    ACTOR_KIND VARCHAR NOT NULL,
    MIGRATION VARCHAR,
    HOLIDAY_ID BIGINT,
    CALENDAR_ID BIGINT,
    HOLIDAY_DATE DATE,
    HOLIDAY_NAME VARCHAR,
    ACTIVE_FLAG VARCHAR,
    CREATED_BY VARCHAR,
    CREATE_DATE TIMESTAMP,
    UPDATED_BY VARCHAR,
    UPDATED_DATE TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT '1970-01-01 00:00:00.000000+00:00'
);
ALTER TABLE CFG_PIPELINES ADD COLUMN CALENDAR_ID BIGINT REFERENCES CFG_CALENDARS(CALENDAR_ID);
ALTER TABLE CFG_PIPELINES ADD COLUMN NON_BUSINESS_DAY VARCHAR(17) NOT NULL DEFAULT 'SKIP' CHECK (NON_BUSINESS_DAY IN ('SKIP','NEXT_BUSINESS_DAY'));
CREATE INDEX ix_pipelines_calendar ON CFG_PIPELINES (CALENDAR_ID) WHERE CALENDAR_ID IS NOT NULL;
CREATE INDEX ix_sql_edits_calendars ON AUD_CFG_CALENDARS_HISTORY(PROJECT_ID) WHERE substr(ACTOR,1,4)='sql:';
CREATE INDEX ix_sql_edits_calendar_holidays ON AUD_CFG_CALENDAR_HOLIDAYS_HISTORY(CALENDAR_ID) WHERE substr(ACTOR,1,4)='sql:';
CREATE TRIGGER trg_project_scope_cfg_calendars_insert BEFORE INSERT ON CFG_CALENDARS
WHEN etl_craft_migration_project() IS NOT NULL AND (NEW.PROJECT_ID IS NOT etl_craft_migration_project())
BEGIN
 SELECT RAISE(ABORT, 'CFG_CALENDARS: a project migration writes only its own project''s rows; filter on (SELECT PROJECT_ID FROM ETL_CRAFT_PROJECT)');
END;
