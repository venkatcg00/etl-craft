-- A pipeline's calendar belongs to the pipeline's own project.
CREATE TRIGGER trg_pipelines_calendar_project_insert BEFORE INSERT ON CFG_PIPELINES
WHEN NEW.CALENDAR_ID IS NOT NULL AND (SELECT c.PROJECT_ID FROM CFG_CALENDARS c WHERE c.CALENDAR_ID=NEW.CALENDAR_ID) IS NOT NEW.PROJECT_ID
BEGIN
 SELECT RAISE(ABORT, 'CFG_PIPELINES: CALENDAR_ID must name a calendar of the pipeline''s own project');
END;
CREATE TRIGGER trg_pipelines_calendar_project_update BEFORE UPDATE OF CALENDAR_ID, PROJECT_ID ON CFG_PIPELINES
WHEN NEW.CALENDAR_ID IS NOT NULL AND (SELECT c.PROJECT_ID FROM CFG_CALENDARS c WHERE c.CALENDAR_ID=NEW.CALENDAR_ID) IS NOT NEW.PROJECT_ID
BEGIN
 SELECT RAISE(ABORT, 'CFG_PIPELINES: CALENDAR_ID must name a calendar of the pipeline''s own project');
END;
