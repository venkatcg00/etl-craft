CREATE TEMP TABLE token_sequence AS SELECT name, seq FROM sqlite_sequence WHERE name='CFG_API_TOKENS';
CREATE TABLE CFG_API_TOKENS_new (
    TOKEN_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    NAME VARCHAR(128) NOT NULL,
    TOKEN_SHA256 VARCHAR(64) NOT NULL UNIQUE,
    PROJECT_ID BIGINT,
    CREATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    EXPIRES_AT TIMESTAMP,
    REVOKED_AT TIMESTAMP,
    ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    UPDATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    ACCOUNT_ID BIGINT NOT NULL REFERENCES CFG_ACCOUNTS(ACCOUNT_ID),
    TOKEN_KIND VARCHAR(8) NOT NULL DEFAULT 'SERVICE' CONSTRAINT ck_api_token_kind CHECK (TOKEN_KIND IN ('SERVICE','ACCESS','REFRESH','AGENT','ATTEMPT')),
    REFRESH_TOKEN_ID BIGINT REFERENCES CFG_API_TOKENS(TOKEN_ID) CONSTRAINT ck_api_token_refresh CHECK (REFRESH_TOKEN_ID IS NULL OR TOKEN_KIND='ACCESS'),
    SSO_GROUP_IDS TEXT NOT NULL DEFAULT '[]',
    POOL VARCHAR(128) REFERENCES CFG_POOLS(POOL_NAME),
    ATTEMPT_ID BIGINT REFERENCES AUD_TASK_ATTEMPTS(ATTEMPT_ID) ON DELETE CASCADE,
    LAST_USED_AT TIMESTAMP,
    CONSTRAINT ck_api_token_attempt CHECK ((TOKEN_KIND='ATTEMPT') = (ATTEMPT_ID IS NOT NULL)),
    CONSTRAINT ck_api_token_pool CHECK (POOL IS NULL OR TOKEN_KIND='AGENT')
);
