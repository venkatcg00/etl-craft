-- Bound live scheduling reads independently of completed run history.
CREATE INDEX ix_pipeline_runs_pending ON AUD_PIPELINES_RUN_LOG (PIPELINE_ID, PIPELINE_RUN_ID)
    WHERE STATUS IN ('QUEUED', 'IN-PROGRESS');
CREATE INDEX ix_pipeline_runs_retention ON AUD_PIPELINES_RUN_LOG (PIPELINE_ID, START_DATE);
CREATE INDEX ix_gate_decisions_run ON AUD_GATE_DECISIONS (PIPELINE_RUN_ID, DECISION_ID);
CREATE INDEX ix_rule_runs_task_run ON AUD_BUSINESS_RULES_RUN_LOG (TASK_RUN_ID);
CREATE INDEX ix_consumption_upstream_run ON AUD_DEPENDENCY_CONSUMPTION (CONSUMED_PIPELINE_RUN_ID);
CREATE INDEX ix_consumption_upstream_task ON AUD_DEPENDENCY_CONSUMPTION (CONSUMED_TASK_RUN_ID)
    WHERE CONSUMED_TASK_RUN_ID IS NOT NULL;
CREATE INDEX ix_consumption_retention ON AUD_DEPENDENCY_CONSUMPTION (CONSUMED_AT);
CREATE INDEX ix_interventions_pipeline_run ON AUD_RUN_INTERVENTIONS (PIPELINE_ID, PIPELINE_RUN_ID);
CREATE INDEX ix_actions_docs_requested ON AUD_ACTIONS (ACTION_ID DESC)
    WHERE COMMAND = 'generate-docs' AND OUTCOME = 'REQUESTED';
