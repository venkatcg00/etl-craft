CREATE TABLE AUD_ANNOUNCEMENTS (
    ANNOUNCEMENT_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    LEVEL VARCHAR(8) NOT NULL CHECK (LEVEL IN ('INFO','WARNING','CRITICAL')),
    MESSAGE VARCHAR(500) NOT NULL,
    STARTS_AT TIMESTAMP NOT NULL,
    ENDS_AT TIMESTAMP,
    REASON VARCHAR NOT NULL,
    CREATED_BY VARCHAR NOT NULL,
    CREATED_BY_KIND VARCHAR NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    ENDED_BY VARCHAR,
    ENDED_BY_KIND VARCHAR,
    ENDED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT '1970-01-01 00:00:00.000000+00:00',
    CHECK (ENDS_AT IS NULL OR ENDS_AT > STARTS_AT)
);
CREATE INDEX ix_announcements_current ON AUD_ANNOUNCEMENTS (STARTS_AT) WHERE ENDED_AT IS NULL;
CREATE TRIGGER trg_actor_guard_aud_announcements_insert BEFORE INSERT ON AUD_ANNOUNCEMENTS
BEGIN
