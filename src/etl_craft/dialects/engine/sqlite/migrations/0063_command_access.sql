CREATE TABLE CFG_PIPELINE_GRANTS_new (
    PIPELINE_GRANT_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    GROUP_ID BIGINT REFERENCES CFG_GROUPS(GROUP_ID),
    ACCOUNT_ID BIGINT REFERENCES CFG_ACCOUNTS(ACCOUNT_ID),
    GRANTEE_ROLE VARCHAR(16) CHECK (GRANTEE_ROLE IN ('viewer','operator')),
    PIPELINE_CODE VARCHAR,
    TAG VARCHAR,
    ROLE VARCHAR(16) NOT NULL CHECK (ROLE IN ('CAN_VIEW','CAN_RUN','CAN_MANAGE')),
    ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    CREATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PROJECT_ID BIGINT NOT NULL DEFAULT 1 REFERENCES CFG_PROJECTS(PROJECT_ID),
    FOREIGN KEY (PROJECT_ID,PIPELINE_CODE) REFERENCES CFG_PIPELINES(PROJECT_ID,PIPELINE_CODE),
    CHECK ((CASE WHEN GROUP_ID IS NULL THEN 0 ELSE 1 END +
            CASE WHEN ACCOUNT_ID IS NULL THEN 0 ELSE 1 END +
            CASE WHEN GRANTEE_ROLE IS NULL THEN 0 ELSE 1 END)=1),
    CHECK ((PIPELINE_CODE IS NULL) <> (TAG IS NULL))
);
