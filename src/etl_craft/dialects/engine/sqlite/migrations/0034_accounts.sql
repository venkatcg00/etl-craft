-- etl-craft: check-account-token-identities
-- etl-craft: rebuild-metadata
CREATE TABLE CFG_ACCOUNTS (
    ACCOUNT_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    ACCOUNT_NAME VARCHAR(128) NOT NULL UNIQUE CHECK (length(trim(ACCOUNT_NAME)) BETWEEN 1 AND 128),
    ACCOUNT_KIND VARCHAR(16) NOT NULL CHECK (ACCOUNT_KIND IN ('USER','SERVICE')),
    ROLE VARCHAR(16) NOT NULL CHECK (ROLE IN ('viewer','operator','developer','admin')),
    EMAIL VARCHAR(320),
    PASSWORD_HASH TEXT,
    OIDC_SUBJECT TEXT UNIQUE,
    ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    CREATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    UPDATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    CHECK (ACCOUNT_KIND = 'USER' OR PASSWORD_HASH IS NULL)
);

CREATE TRIGGER trg_accounts_no_delete BEFORE DELETE ON CFG_ACCOUNTS
BEGIN
    SELECT RAISE(ABORT, 'CFG_ACCOUNTS cannot be deleted; disable the account with ACTIVE_FLAG=N');
END;

INSERT INTO CFG_ACCOUNTS (ACCOUNT_NAME, ACCOUNT_KIND, ROLE, CREATED_BY, UPDATED_BY)
SELECT NAME AS account_name, 'SERVICE' AS account_kind, ROLE AS role, etl_craft_actor() AS created_by, etl_craft_actor() AS updated_by FROM CFG_API_TOKENS ORDER BY TOKEN_ID;

CREATE TEMP TABLE etl_craft_token_sequence AS SELECT seq AS seq FROM sqlite_sequence WHERE name='CFG_API_TOKENS';
CREATE TABLE CFG_API_TOKENS_new (
    TOKEN_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    NAME VARCHAR(128) NOT NULL,
    TOKEN_SHA256 VARCHAR(64) NOT NULL UNIQUE,
    ROLE VARCHAR(16) NOT NULL CHECK (ROLE IN ('viewer', 'operator', 'admin')),
    PROJECT_ID BIGINT,
    CREATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    CREATE_DATE TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    EXPIRES_AT TIMESTAMP,
    REVOKED_AT TIMESTAMP,
    ACTIVE_FLAG VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (ACTIVE_FLAG IN ('Y','N')),
    UPDATED_BY VARCHAR(128) NOT NULL DEFAULT 'etl-craft',
    UPDATED_DATE TIMESTAMP NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%f', 'now') || '000+00:00'),
    ACCOUNT_ID BIGINT NOT NULL REFERENCES CFG_ACCOUNTS(ACCOUNT_ID)
);
INSERT INTO CFG_API_TOKENS_new (TOKEN_ID, NAME, TOKEN_SHA256, ROLE, PROJECT_ID, CREATED_BY, CREATE_DATE, EXPIRES_AT, REVOKED_AT, ACTIVE_FLAG, UPDATED_BY, UPDATED_DATE, ACCOUNT_ID)
SELECT t.TOKEN_ID AS token_id, t.NAME AS name, t.TOKEN_SHA256 AS token_sha256, t.ROLE AS role, t.PROJECT_ID AS project_id, t.CREATED_BY AS created_by, t.CREATE_DATE AS create_date, t.EXPIRES_AT AS expires_at, t.REVOKED_AT AS revoked_at, t.ACTIVE_FLAG AS active_flag, t.UPDATED_BY AS updated_by, t.UPDATED_DATE AS updated_date, a.ACCOUNT_ID AS account_id
FROM CFG_API_TOKENS t JOIN CFG_ACCOUNTS a ON a.ACCOUNT_NAME=t.NAME;
DROP TABLE CFG_API_TOKENS;
ALTER TABLE CFG_API_TOKENS_new RENAME TO CFG_API_TOKENS;
ALTER TABLE CFG_API_TOKENS DROP COLUMN ROLE;
UPDATE sqlite_sequence SET seq=max(seq, coalesce((SELECT seq AS seq FROM etl_craft_token_sequence), seq)) WHERE name='CFG_API_TOKENS';
INSERT INTO sqlite_sequence (name,seq) SELECT 'CFG_API_TOKENS' AS name,seq AS seq FROM etl_craft_token_sequence WHERE NOT EXISTS (SELECT 1 AS present FROM sqlite_sequence WHERE name='CFG_API_TOKENS');
DROP TABLE etl_craft_token_sequence;
