-- A terminal outcome stays immutable when its external log is acknowledged.
DROP TRIGGER trg_actor_guard_aud_task_attempts_update;
CREATE TRIGGER trg_actor_guard_aud_task_attempts_update BEFORE UPDATE ON AUD_TASK_ATTEMPTS
BEGIN
    SELECT CASE WHEN etl_craft_actor() IS NULL THEN RAISE(ABORT, 'AUD_TASK_ATTEMPTS is written only by etl-craft; use etl-craft mark, cancel or run, or a project migration (etl-craft migrate)') END;
    SELECT CASE WHEN etl_craft_purpose() <> 'retention' AND OLD.STATUS NOT IN ('QUEUED','CLAIMED','RUNNING') AND NOT (
        (OLD.LOG_PATH IS NULL OR NEW.LOG_PATH IS OLD.LOG_PATH)
        AND NEW.ATTEMPT_ID IS OLD.ATTEMPT_ID
        AND NEW.TASK_RUN_ID IS OLD.TASK_RUN_ID
        AND NEW.ATTEMPT_NUMBER IS OLD.ATTEMPT_NUMBER
        AND NEW.STATUS IS OLD.STATUS
        AND NEW.OWNER_ID IS OLD.OWNER_ID
        AND NEW.LEASE_EXPIRES_AT IS OLD.LEASE_EXPIRES_AT
        AND NEW.HEARTBEAT_AT IS OLD.HEARTBEAT_AT
        AND NEW.QUEUED_AT IS OLD.QUEUED_AT
        AND NEW.CLAIMED_AT IS OLD.CLAIMED_AT
        AND NEW.STARTED_AT IS OLD.STARTED_AT
        AND NEW.ENDED_AT IS OLD.ENDED_AT
        AND NEW.HOST IS OLD.HOST
        AND NEW.PID IS OLD.PID
        AND NEW.PROCESS_START IS OLD.PROCESS_START
        AND NEW.EXIT_CODE IS OLD.EXIT_CODE
        AND NEW.SOURCE_COUNT IS OLD.SOURCE_COUNT
        AND NEW.TARGET_COUNT IS OLD.TARGET_COUNT
        AND NEW.INSERT_COUNT IS OLD.INSERT_COUNT
        AND NEW.UPDATE_COUNT IS OLD.UPDATE_COUNT
        AND NEW.DELETE_COUNT IS OLD.DELETE_COUNT
        AND NEW.ROWS_WRITTEN IS OLD.ROWS_WRITTEN
        AND NEW.ERROR_MESSAGE IS OLD.ERROR_MESSAGE
        AND NEW.TASK_LOG IS OLD.TASK_LOG
        AND NEW.REQUESTED_BY IS OLD.REQUESTED_BY
        AND NEW.REQUESTED_BY_KIND IS OLD.REQUESTED_BY_KIND
        AND NEW.NOT_BEFORE IS OLD.NOT_BEFORE
        AND NEW.RETRYABLE IS OLD.RETRYABLE
        AND NEW.REJECT_COUNT IS OLD.REJECT_COUNT
        AND NEW.WATERMARK_FROM IS OLD.WATERMARK_FROM
        AND NEW.WATERMARK_TO IS OLD.WATERMARK_TO
        AND NEW.FAILURE_CLASS IS OLD.FAILURE_CLASS
        AND NEW.FAILURE_SOURCE IS OLD.FAILURE_SOURCE
        AND NEW.FAILURE_CODE IS OLD.FAILURE_CODE
        AND NEW.RETRY_ON IS OLD.RETRY_ON
        AND NEW.POOL IS OLD.POOL
        AND NEW.SLOT_KIND IS OLD.SLOT_KIND
        AND NEW.PRIORITY IS OLD.PRIORITY
        AND NEW.CANCEL_REQUESTED_AT IS OLD.CANCEL_REQUESTED_AT
        AND NEW.CANCEL_ACKNOWLEDGED_AT IS OLD.CANCEL_ACKNOWLEDGED_AT
        AND NEW.FORCE_FLAG IS OLD.FORCE_FLAG
        AND NEW.RERUN_FLAG IS OLD.RERUN_FLAG
        AND NEW.RESERVED_CPU IS OLD.RESERVED_CPU
        AND NEW.RESERVED_MEMORY_MB IS OLD.RESERVED_MEMORY_MB
        AND NEW.LOG_REMOVED_AT IS OLD.LOG_REMOVED_AT
    ) THEN RAISE(ABORT, 'AUD_TASK_ATTEMPTS immutable history; use a new action or etl-craft retention') END;
END;

CREATE INDEX ix_attempt_log_pending ON AUD_TASK_ATTEMPTS (ATTEMPT_ID)
WHERE LOG_PATH IS NULL AND LOG_REMOVED_AT IS NULL
AND STATUS NOT IN ('QUEUED','CLAIMED','RUNNING');
