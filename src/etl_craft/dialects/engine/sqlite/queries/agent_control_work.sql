SELECT a.ATTEMPT_ID AS attempt_id, a.STATUS AS status, a.SLOT_KIND AS slot_kind,
a.OWNER_ID AS owner_id, a.CANCEL_REQUESTED_AT AS cancel_requested_at,
0 AS cleanup, a.LEASE_EXPIRES_AT AS lease_expires_at, t.TASK_RUN_ID AS task_run_id
FROM AUD_TASK_ATTEMPTS a JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID=a.TASK_RUN_ID
WHERE a.OWNER_ID=:owner AND a.STATUS IN ('CLAIMED','RUNNING')
UNION
SELECT a.ATTEMPT_ID AS attempt_id, a.STATUS AS status, a.SLOT_KIND AS slot_kind,
a.OWNER_ID AS owner_id, a.CANCEL_REQUESTED_AT AS cancel_requested_at,
1 AS cleanup, a.LEASE_EXPIRES_AT AS lease_expires_at, t.TASK_RUN_ID AS task_run_id
FROM AUD_CONTROL_REQUESTS c CROSS JOIN json_each(c.ATTEMPT_IDS) ids
JOIN AUD_TASK_ATTEMPTS a ON a.ATTEMPT_ID=CAST(ids.value AS bigint)
JOIN AUD_TASK_RUN_LOG t ON t.TASK_RUN_ID=a.TASK_RUN_ID
WHERE c.STATUS <> 'COMPLETED' AND a.OWNER_ID=:owner
AND a.STATUS NOT IN ('CLAIMED','RUNNING','QUEUED')
AND NOT EXISTS (SELECT 1 FROM AUD_ATTEMPT_ACKNOWLEDGEMENTS ack
WHERE ack.ATTEMPT_ID=a.ATTEMPT_ID AND ack.KIND='QUERIES')
