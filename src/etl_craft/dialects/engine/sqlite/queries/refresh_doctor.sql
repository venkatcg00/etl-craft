SELECT p.PIPELINE_CODE AS pipeline_code,r.STATUS AS status,r.FINDINGS AS findings,
p.BLOCK_ON_REFRESH_ERROR AS block_on_refresh_error,
EXISTS(SELECT 1 FROM AUD_PIPELINE_REFRESHES good WHERE good.PIPELINE_ID=p.PIPELINE_ID AND good.STATUS='SUCCESS') AS has_baseline
FROM CFG_PIPELINES p
LEFT JOIN AUD_PIPELINE_REFRESHES r ON r.REFRESH_ID=(SELECT MAX(latest.REFRESH_ID) FROM AUD_PIPELINE_REFRESHES latest WHERE latest.PIPELINE_ID=p.PIPELINE_ID)
WHERE p.PROJECT_ID=:project_id AND p.ACTIVE_FLAG='Y' AND (r.STATUS='FAILED' OR r.REFRESH_ID IS NULL)
ORDER BY p.PIPELINE_CODE
